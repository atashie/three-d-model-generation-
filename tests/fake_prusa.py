"""A stand-in for prusa-slicer-console.exe, run as [sys.executable, fake_prusa.py, ...args].

It accepts only the two argument forms tdmg.portability builds (the measured forms):
    --info MODEL.stl
    --export-gcode MODEL.stl -o OUT.gcode --bed-shape B --max-print-height H
        --nozzle-diameter N --layer-height L --first-layer-height F --filament-diameter D
Anything else exits 1, as every measured PrusaSlicer error did.

By default it reports what the real one reported for a good model: --info prints the STL's
size, facet count, "manifold = yes", one part and the volume, to 6 decimals, from the STL
itself; --export-gcode writes a G-code whose line 1 is the "; generated by PrusaSlicer
2.9.7 on <date> at <time> UTC" line, then one ";LAYER_CHANGE" and ";Z:" per layer for the
STL's height at the given layer heights.

Its behaviour comes from the JSON file in $TDMG_FAKE_PRUSA_CONTROL, if set:
    info_exit    exit code of --info (default 0)
    info_stdout  the whole --info stdout instead of the computed one
    info         {key: value} added to or replacing --info lines; a null value drops it
    gcode_exit   exit code of --export-gcode (default 0)
    gcode        write the G-code (default true)
    layers       the number of layers written (default: the STL's height)
    last_z       the text of the last ";Z:" line (default: the layer's height)
    z            {"<layer number, from 1>": text, or null to leave that ";Z:" line out}
    gcode_empty  write an empty G-code file
    stderr_cwd_pad  write the working folder's path to stderr, then this many "y"
    stdout       text printed to stdout by --export-gcode (default: "Slicing result exported
                 to OUT.gcode", with the full path, as the real one prints)
    stderr       text written to stderr by both forms
    sleep        seconds to wait first (default 0)
"""

import datetime
import json
import os
import sys
import time
from pathlib import Path

import numpy as np

SETTINGS = ["--bed-shape", "--max-print-height", "--nozzle-diameter", "--layer-height",
            "--first-layer-height", "--filament-diameter"]


# A binary STL: an 80-byte header, a uint32 count, then 50 bytes per facet.
FACET = np.dtype([("normal", "<f4", 3), ("vertices", "<f4", (3, 3)), ("attr", "<u2")])


def _triangles(stl: Path) -> np.ndarray:
    """(N, 3, 3) vertices, float32 widened to float64 (numpy only, so the fake starts fast)."""
    data = stl.read_bytes()
    count = int(np.frombuffer(data, "<u4", 1, 80)[0])
    return np.frombuffer(data, FACET, count, 84)["vertices"].astype(np.float64)


def _info(stl: Path, control: dict) -> str:
    tri = _triangles(stl)
    v = tri.reshape(-1, 3)
    volume = np.einsum("ij,ij->i", tri[:, 0], np.cross(tri[:, 1], tri[:, 2])).sum() / 6
    lo, hi = v.min(axis=0), v.max(axis=0)
    values = {f"size_{a}": f"{hi[i] - lo[i]:.6f}" for i, a in enumerate("xyz")}
    values |= {f"min_{a}": f"{lo[i]:.6f}" for i, a in enumerate("xyz")}
    values |= {f"max_{a}": f"{hi[i]:.6f}" for i, a in enumerate("xyz")}
    values |= {"number_of_facets": str(len(tri)), "manifold": "yes",
               "number_of_parts": " 1", "volume": f"{volume:.6f}"}
    for key, value in control.get("info", {}).items():
        if value is None:
            values.pop(key, None)
        else:
            values[key] = str(value)
    return f"[{stl.name}]\n" + "".join(f"{k} = {v}\n" for k, v in values.items())


def _gcode(stl: Path, settings: dict, control: dict) -> str:
    z = _triangles(stl)[:, :, 2]
    first, layer = float(settings["--first-layer-height"]), float(settings["--layer-height"])
    n = control.get("layers", 1 + round((z.max() - z.min() - first) / layer))
    now = datetime.datetime.now(datetime.UTC)
    out = [f"; generated by PrusaSlicer 2.9.7 on {now:%Y-%m-%d} at {now:%H:%M:%S.%f} UTC", "",
           "; external perimeters extrusion width = 0.45mm", "G28"]
    for i in range(n):
        top = f"{first + i * layer:.6g}"
        if i == n - 1 and "last_z" in control:
            top = str(control["last_z"])
        z = control.get("z", {}).get(str(i + 1), top)
        out += [";LAYER_CHANGE", *([] if z is None else [f";Z:{z}"]), f";HEIGHT:{layer:g}",
                f"G1 Z{top}", "G1 X10 Y10 E1"]
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    env = os.environ.get("TDMG_FAKE_PRUSA_CONTROL")
    control = json.loads(Path(env).read_text()) if env and Path(env).is_file() else {}
    if "stderr" in control:
        sys.stderr.write(control["stderr"])
        sys.stderr.flush()
    if "stderr_cwd_pad" in control:
        sys.stderr.write(os.getcwd() + "\n" + "y" * control["stderr_cwd_pad"])
        sys.stderr.flush()
    time.sleep(control.get("sleep", 0))
    if len(argv) == 2 and argv[0] == "--info":
        mode, stl = "info", Path(argv[1])
    elif (len(argv) == 4 + 2 * len(SETTINGS) and argv[0] == "--export-gcode"
          and argv[2] == "-o" and argv[4::2] == SETTINGS):
        mode, stl = "gcode", Path(argv[1])
        out, settings = Path(argv[3]), dict(zip(argv[4::2], argv[5::2], strict=True))
    else:
        sys.stderr.write(f"fake: unexpected arguments {argv}\n")
        return 1
    if not stl.is_file():
        sys.stderr.write(f"No such file: {stl}\n")
        return 1
    if mode == "info":
        sys.stdout.write(control["info_stdout"] if "info_stdout" in control
                         else _info(stl, control))
        return control.get("info_exit", 0)
    sys.stdout.write(control.get("stdout", f"Slicing result exported to {out}\n"))
    if control.get("gcode_empty"):
        out.write_bytes(b"")
    elif control.get("gcode", True):
        out.write_bytes(_gcode(stl, settings, control).encode())
    return control.get("gcode_exit", 0)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
