# --- G-code and field rules ----------------------------------------------------------------------

def _orca(stamp: str, body: str = "G28\n") -> bytes:
    return f"; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.5.0 on {stamp}\n{body}".encode()


def test_gcode_allowance():
    a, b = _orca("2026-11-16 at 15:11:34"), _orca("2026-11-17 at 09:00:00")
    assert compare_file("slice", "plate_1.gcode", a, b) is None
    assert compare_file("slice", "face-down/plate_1.gcode.failed", a, b) is None
    # Fractional seconds, another version, another line: not the measured form.
    frac = _orca("2026-11-17 at 09:00:00.123456")
    assert "not the measured timestamp line" in compare_file("slice", "plate_1.gcode", a, frac)
    other = _orca("2026-11-17 at 09:00:00", "G28 X1\n")
    assert "line 3 differs" in compare_file("slice", "plate_1.gcode", a, other)
    assert "lines against" in compare_file("slice", "plate_1.gcode", a, a + b"G1\n")
    # PrusaSlicer's: line 1, UTC.
    pa = b"; generated by PrusaSlicer 2.9.7 on 2026-11-16 at 20:11:42 UTC\n\nG28\n"
    pb = b"; generated by PrusaSlicer 2.9.7 on 2026-11-17 at 08:00:00 UTC\n\nG28\n"
    assert compare_file("slice", "prusaslicer.portability-only.gcode.txt", pa, pb) is None
    # A G-code name outside the slice stage, or another file, gets no allowance.
    assert compare_file("flat", "plate_1.gcode", a, b) == "flat/plate_1.gcode: bytes differ"
    assert set(GCODE_TIMESTAMPS) == {"plate_1.gcode", "plate_1.gcode.failed",
                                     "prusaslicer.portability-only.gcode.txt",
                                     "prusaslicer.portability-only.gcode.txt.failed"}


def _readme_form(path) -> str:
    """A VOLATILE_FIELDS path as the repeatability record writes it."""
    return "$" + "".join(f'["{k}"]' if "/" in k or "." in k else f".{k}" for k in path)


def test_volatile_fields_are_the_repeatability_table():
    """Each is a slice.json row of the record's table; the unmeasured forms are not."""
    readme = (REPO_ROOT / library.REPEATABILITY).read_text(encoding="utf-8")
    table = readme[readme.index("## Fields that differ"):readme.index("Inferred, not measured")]
    for path in VOLATILE_FIELDS:
        assert _readme_form(path) in table, path
    inferred = readme[readme.index("Inferred, not measured"):readme.index("No other field")]
    for path in VOLATILE_FIELDS:
        assert _readme_form(path) not in inferred, path
    h = "a" * 64

    def masked(rec):
        return library._masked(rec)
    rec = {"outputs": {"plate_1.gcode": h, "plate_1.gcode.failed": h,
                       "face-up/plate_1.gcode.failed": h,
                       "glue-color-2-f0f10a/plate_1.gcode.failed": h,
                       "prusaslicer.portability-only.gcode.txt.failed": h,
                       "glue-x/plate_1.gcode": h},
           "faces": {"up": {"gcode": {"sha256": h, "normalised_sha256": h}}},
           "glue": {"plates": {"glue-base": {"portability": {"gcode": {"sha256": h}}}}}}
    m = masked(rec)
    assert m["outputs"]["plate_1.gcode"] != h
    assert m["outputs"]["glue-color-2-f0f10a/plate_1.gcode.failed"] != h
    # Inferred, not measured: kept.
    assert m["outputs"]["plate_1.gcode.failed"] == h
    assert m["outputs"]["face-up/plate_1.gcode.failed"] == h
    assert m["outputs"]["prusaslicer.portability-only.gcode.txt.failed"] == h
    assert m["outputs"]["glue-x/plate_1.gcode"] == h          # not a glue plate's name
    assert m["faces"]["up"]["gcode"]["normalised_sha256"] == h
    assert m["faces"]["up"]["gcode"]["sha256"] != h
    assert m["glue"]["plates"]["glue-base"]["portability"]["gcode"]["sha256"] != h
    # A volatile path that does not hold a SHA-256 is compared as it is.
    assert masked({"gcode": {"sha256": None}}) == {"gcode": {"sha256": None}}


