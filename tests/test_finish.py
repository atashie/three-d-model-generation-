def _git(root: Path, *args) -> str:
    done = subprocess.run(["git", "-C", str(root), "-c", "user.name=t", "-c",
                           "user.email=t@example.com", "-c", "commit.gpgsign=false",
                           *map(str, args)], check=False, capture_output=True, text=True)
    assert done.returncode in (0, 1), done.stderr
    return done.stdout


