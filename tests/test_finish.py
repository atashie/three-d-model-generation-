_TEMPLATES: dict[str, Path] = {}


def _build(where: Path, kind: str, orca, proot) -> Path:
    image = _png(where / "in" / "roadie.png", roadie_like())
    jobs_dir = where / "jobs"
    name = R1 if kind == "r1" else R2
    colors = [] if kind == "r1" else ["--colors"]
    r = _invoke("job", "new", name, "--class", "flat-icon", "--image", image, "--jobs-dir",
                jobs_dir, *colors)
    assert r.exit_code == 0, r.output
    sets = ([*R1_SELECT, "flat.width_mm=60", "flat.thickness_mm=3"] if kind == "r1"
            else ["colors.width_mm=60", "colored_flat.thickness_mm=3"])
    r = _invoke("job", "set", name, *sets, "--jobs-dir", jobs_dir)
    assert r.exit_code == 0, r.output
    r = _invoke("job", "run", name, "--jobs-dir", jobs_dir, "--slicer-dir", orca,
                "--prusaslicer-dir", proot)
    assert r.exit_code in (0, 1), r.output
    return jobs_dir / name


def _job(tmp_path, tmp_path_factory, slicers, kind="r1", jobs_dir=None) -> Path:
    """A run job of this kind in jobs_dir (default tmp_path/jobs)."""
    if kind not in _TEMPLATES:
        _TEMPLATES[kind] = _build(tmp_path_factory.mktemp(f"template-{kind}"), kind,
                                  *slicers)
    src = _TEMPLATES[kind]
    jobs_dir = tmp_path / "jobs" if jobs_dir is None else jobs_dir
    jobs_dir.mkdir(parents=True, exist_ok=True)
    dest = jobs_dir / src.name
    shutil.copytree(src, dest)
    return dest


def _confirm(folder, proot, *args, words=WORDS):
    r = _invoke("job", "confirm", folder.name, "--subject", "print", "--owner-said", words,
                "--jobs-dir", folder.parent, "--prusaslicer-dir", proot, *args)
    assert r.exit_code == 0, r.output
    return r


def _ready(tmp_path, tmp_path_factory, slicers, kind="r1", confirm=(), jobs_dir=None):
    folder = _job(tmp_path, tmp_path_factory, slicers, kind, jobs_dir)
    args = confirm or (["--accept-not-certified"] if kind == "r1" else
                       ["--face", "down", "--accept-not-certified"])
    _confirm(folder, slicers[1], *args)
    return folder


def _finish(folder, slicers, *args, public="no", purge=PURGE, prints=None):
    prints = folder.parent.parent / "prints" if prints is None else prints
    extra = [] if public is None else ["--public", public]
    extra += [] if purge is None else ["--purge-owner-said", purge]
    return _invoke("finish", folder.name, *extra, "--jobs-dir", folder.parent,
                   "--prints-dir", prints, "--slicer-dir", slicers[0],
                   "--prusaslicer-dir", slicers[1], *args)


def _call(folder, slicers, *, public=False, purge=PURGE, prints=None, **kw):
    """finish() itself, for the interruption tests (a Crash passes through it)."""
    prints = folder.parent.parent / "prints" if prints is None else prints
    lines = []
    finish(folder.name, public=public, purge_owner_said=purge,
           machine=Machine(slicers[0], slicers[1]), jobs_dir=folder.parent,
           prints_dir=prints, say=lines.append, **kw)
    return lines


def _tree(root: Path) -> dict[str, str]:
    if not root.exists():
        return {}
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(root.rglob("*")) if p.is_file()}


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


