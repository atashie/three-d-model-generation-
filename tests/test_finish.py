def _symlink(link: Path, target: Path) -> None:
    try:
        link.symlink_to(target, target_is_directory=True)
    except OSError as e:
        pytest.skip(f"this account cannot create symlinks ({e})")


def _junction(link: Path, target: Path) -> None:
    if sys.platform != "win32":
        pytest.skip("junctions are Windows only")
    done = subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)],
                          check=False, capture_output=True, text=True)
    assert done.returncode == 0, done.stdout + done.stderr
    assert link.is_junction()


@pytest.mark.parametrize("make", [_symlink, _junction], ids=["symlink", "junction"])
@pytest.mark.parametrize("where", ["prints", "jobs", "job"])
def test_links_are_refused(tmp_path, tmp_path_factory, slicers, repo, make, where):
    real_jobs = tmp_path / "real-jobs"
    folder = _ready(tmp_path, tmp_path_factory, slicers, jobs_dir=real_jobs)
    before = _tree(folder)
    jobs_dir, prints = real_jobs, tmp_path / "prints"
    if where == "prints":
        (tmp_path / "elsewhere").mkdir()
        make(prints, tmp_path / "elsewhere")
    elif where == "jobs":
        jobs_dir = tmp_path / "jobs-link"
        make(jobs_dir, real_jobs)
    else:
        jobs_dir = tmp_path / "jobs-of-links"
        jobs_dir.mkdir()
        make(jobs_dir / R1, folder)
    try:
        r = _invoke("finish", R1, "--public", "no", "--purge-owner-said", PURGE,
                    "--jobs-dir", jobs_dir, "--prints-dir", prints, "--slicer-dir",
                    slicers[0], "--prusaslicer-dir", slicers[1])
        assert r.exit_code == 2 and "is a link" in _plain(r.output)
        assert _tree(folder) == before
        assert not (tmp_path / "elsewhere" / R1).exists()
    finally:
        for link in (prints, tmp_path / "jobs-link", tmp_path / "jobs-of-links" / R1):
            if link.is_symlink() or link.is_junction():
                os.rmdir(link) if link.is_junction() else link.unlink()


