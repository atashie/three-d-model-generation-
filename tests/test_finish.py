def test_a_rebuild_that_differs(tmp_path, tmp_path_factory, slicers, repo, monkeypatch):
    folder = _ready(tmp_path, tmp_path_factory, slicers)
    before = _tree(folder)
    real = tdmg.job_runner.RUNNERS["flat"]

    def patched(f, job, p, inputs, out, machine):     # a code change in the flat stage
        return real(f, job, {**p, "smooth_px": 0.0}, inputs, out, machine)
    monkeypatch.setitem(tdmg.job_runner.RUNNERS, "flat", patched)
    r = _finish(folder, slicers)
