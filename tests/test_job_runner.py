def _invoke(*args):
    return runner.invoke(app, [str(a) for a in args])


def _new(tmp_path, name, *, colors=False, rgba=None, extra=()):
    image = _png(tmp_path / "in" / "roadie.png", roadie_like() if rgba is None else rgba)
    jobs_dir = tmp_path / "jobs"
    result = _invoke("job", "new", name, "--class", "flat-icon", "--image", image,
                     "--jobs-dir", jobs_dir, *(["--colors"] if colors else []), *extra)
    assert result.exit_code == 0, result.output
    return jobs_dir / name


def _set(folder, *assignments):
    result = _invoke("job", "set", folder.name, *assignments, "--jobs-dir", folder.parent)
    assert result.exit_code == 0, result.output
    return result


def _run(folder, orca, prusa_root):
    return _invoke("job", "run", folder.name, "--jobs-dir", folder.parent,
                   "--slicer-dir", orca, "--prusaslicer-dir", prusa_root)


def _files(root: Path) -> dict[str, bytes]:
    return {p.relative_to(root).as_posix(): p.read_bytes()
            for p in sorted(root.rglob("*")) if p.is_file()}


def _without_gcode_hashes(obj):
    """slice.json without the hashes of the G-code files (the time of slicing)."""
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            if k == "gcode" and isinstance(v, dict):
                v = {kk: vv for kk, vv in v.items() if kk != "sha256"}
            if k == "outputs" and isinstance(v, dict):
                v = {kk: vv for kk, vv in v.items() if ".gcode" not in kk}
            out[k] = _without_gcode_hashes(v)
        return out
    if isinstance(obj, list):
        return [_without_gcode_hashes(v) for v in obj]
    return obj


def assert_same_outputs(job_stage: Path, hand: Path) -> None:
    a, b = _files(job_stage), _files(hand)
    assert sorted(a) == sorted(b)
    for name in a:
        if ".gcode" in name:
            assert GENERATED.search(a[name]) is not None, name
            assert GENERATED.sub(b"", a[name]) == GENERATED.sub(b"", b[name]), name
        elif Path(name).name == "slice.json":
            ja, jb = json.loads(a[name]), json.loads(b[name])
            assert _without_gcode_hashes(ja) == _without_gcode_hashes(jb), name
        else:
            assert a[name] == b[name], name


def _stage_lines(output: str) -> dict[str, str]:
    lines = {}
    for line in output.splitlines():
        m = re.match(r"(\w+): (ran|done, not run again|waits|failed)", line)
        if m:
            lines[m.group(1)] = m.group(2)
    return lines


# --- R1 and R2 end to end, equal to the stage commands ------------------------------------

def test_r1_job_runs_end_to_end_and_equals_the_stage_commands(tmp_path, slicers):
    orca, proot = slicers
    folder = _new(tmp_path, "roadie")
    _set(folder, *R1_SELECT, "flat.width_mm=60", "flat.thickness_mm=3")
    result = _run(folder, orca, proot)
    assert _stage_lines(result.output) == {"select": "ran", "flat": "ran", "slice": "ran"}
    out = _plain(result.output)
    assert "select: done - one_piece" in out
    assert "flat: done - verdict" in out and "slice: done - verdict" in out
    assert job_runner.CONFIRM_NOTE in out
    assert "check select/preview.png" in out

    hand = tmp_path / "hand"
    image = folder / "source" / "roadie.png"
    codes = [_invoke("select", image, "--out", hand / "select", *R1_HAND_SELECT).exit_code,
             _invoke("flat", hand / "select", "--width-mm", "60", "--thickness-mm", "3",
                     "--out", hand / "flat").exit_code,
             _invoke("slice", hand / "flat", "--out", hand / "slice", "--slicer-dir", orca,
                     "--prusaslicer-dir", proot).exit_code]
    assert set(codes) <= {0, 1}
    assert result.exit_code == max(codes)
    for stage in ("select", "flat", "slice"):
        assert_same_outputs(folder / stage, hand / stage)
    # The job folder holds the stage folders, job.yaml, source/ and state.json, nothing else.
    assert sorted(p.name for p in folder.iterdir()) == ["flat", "job.yaml", "select",
                                                        "slice", "source", STATE_FILE]


