def test_a_linked_stage_folder_is_refused(tmp_path, slicers):
    folder = _r1(tmp_path, slicers)
    target = tmp_path / "elsewhere"
    target.mkdir()
    shutil.rmtree(folder / "flat")
    try:
        (folder / "flat").symlink_to(target, target_is_directory=True)
    except OSError:
        if sys.platform != "win32":
            pytest.skip("this account cannot create symlinks")
        # Windows without the symlink right: a junction, which needs none.
        subprocess.run(["cmd", "/c", "mklink", "/J", str(folder / "flat"), str(target)],
                       check=True, capture_output=True)
        assert (folder / "flat").is_junction()
    result = _run(folder, *slicers)
    assert result.exit_code == 2 and "is a link" in _plain(result.output)


