def _r1(tmp_path, slicers, name="roadie"):
    orca, proot = slicers
    folder = _new(tmp_path, name)
    _set(folder, *R1_SELECT, "flat.width_mm=60", "flat.thickness_mm=3")
    assert _run(folder, orca, proot).exit_code in (0, 1)
    return folder


def _keys(folder: Path, machine: Machine) -> dict[str, str]:
    """Each stage's key from the records now on disk."""
    job = load_job(folder)
    hashes = {s: job_runner._sha((folder / s / job_runner.STAGE_RECORDS[s]).read_bytes())
              for s in job["stages"]}
    return {s: stage_key(job, s, hashes, machine) for s in job["stages"]}


def _mtimes(folder: Path) -> dict[str, int]:
    return {s: (folder / s / job_runner.STAGE_RECORDS[s]).stat().st_mtime_ns
            for s in ("select", "flat", "slice")}


def test_nothing_changed_runs_nothing_and_keeps_state_bytes(tmp_path, slicers):
    folder = _r1(tmp_path, slicers)
    state = (folder / STATE_FILE).read_bytes()
    before = _mtimes(folder)
    result = _run(folder, *slicers)
    assert _stage_lines(result.output) == {s: "done, not run again"
                                           for s in ("select", "flat", "slice")}
    assert _mtimes(folder) == before
    assert (folder / STATE_FILE).read_bytes() == state
    # state.json: canonical JSON of the keys and the SHA-256 of each stage record.
    parsed = json.loads(state)
    assert job_runner.canonical_json(parsed) == state
    assert parsed == {"schema": job_runner.STATE_SCHEMA,
                      "stages": {s: {"key": k, "record_sha256": _sha_file(
                          folder / s / job_runner.STAGE_RECORDS[s])}
                          for s, k in _keys(folder, Machine(None, slicers[1])).items()}}


def test_same_job_elsewhere_gives_the_same_state_bytes(tmp_path, slicers):
    """Except the slice record's hash: slice.json holds G-code hashes, and G-code holds the
    time of slicing (job_runner docstring)."""
    a = _r1(tmp_path / "a", slicers, "one")
    b = _r1(tmp_path / "b", slicers, "two")
    sa, sb = (json.loads((f / STATE_FILE).read_bytes()) for f in (a, b))
    for state in (sa, sb):
        del state["stages"]["slice"]["record_sha256"]
    assert sa == sb


def test_a_parameter_change_reruns_that_stage_and_later_ones_only(tmp_path, slicers):
    folder = _r1(tmp_path, slicers)
    before = _mtimes(folder)
    select_files = _files(folder / "select")
    _set(folder, "flat.thickness_mm=2")
    status = _plain(_invoke("job", "status", folder.name, "--jobs-dir", folder.parent,
                            "--prusaslicer-dir", slicers[1]).output)
    assert "select: done" in status and "flat: stale" in status
    assert "slice: stale (an earlier stage is not done)" in status
    result = _run(folder, *slicers)
    assert _stage_lines(result.output) == {"select": "done, not run again", "flat": "ran",
                                           "slice": "ran"}
    after = _mtimes(folder)
    assert after["select"] == before["select"] and _files(folder / "select") == select_files
    assert after["flat"] != before["flat"]
    assert json.loads((folder / "flat" / "flat.json").read_bytes())["params"][
        "thickness_mm"] == 2.0
    # A select change reruns everything.
    _set(folder, "select.instructions=The bird.")
    assert _stage_lines(_run(folder, *slicers).output) == {s: "ran" for s in
                                                           ("select", "flat", "slice")}


def test_an_interrupted_stage_reruns(tmp_path, slicers):
    folder = _r1(tmp_path, slicers)
    flat = _files(folder / "flat")
    (folder / "flat" / "flat.json").unlink()            # the record is written last
    (folder / "slice.new").mkdir()                      # a run left half way
    (folder / "slice.new" / "x").write_bytes(b"x")
    status = _plain(_invoke("job", "status", folder.name, "--jobs-dir", folder.parent,
                            "--prusaslicer-dir", slicers[1]).output)
    assert "flat: not run (its folder has no record (an interrupted run))" in status
    result = _run(folder, *slicers)
    # flat reruns to the same bytes, so slice's key is unchanged and it is kept.
    assert _stage_lines(result.output) == {"select": "done, not run again", "flat": "ran",
                                           "slice": "done, not run again"}
    assert _files(folder / "flat") == flat
    assert not (folder / "slice.new").exists()


def test_an_interrupted_swap_puts_the_old_folder_back_first(tmp_path, slicers):
    folder = _r1(tmp_path, slicers)
    flat = _files(folder / "flat")
    (folder / "flat").rename(folder / "flat.old")
    (folder / "flat.new").mkdir()
    result = _run(folder, *slicers)
    # state.json still holds the old folder's key, so once it is back nothing reruns.
    assert set(_stage_lines(result.output).values()) == {"done, not run again"}
    assert _files(folder / "flat") == flat
    assert not (folder / "flat.old").exists() and not (folder / "flat.new").exists()


