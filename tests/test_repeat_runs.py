"""scripts/repeat_runs.py: the JSON-diff and comparison helpers (the full run is not a test)."""

import json
import zipfile

import repeat_runs as rr  # scripts/ is on the pytest pythonpath (pyproject.toml)


def test_equal_values_give_no_paths():
    doc = {"a": [1, {"b": None}], "c": "x"}
    assert rr.json_diff_paths(doc, json.loads(json.dumps(doc))) == []


def test_nested_dict_and_list_paths():
    a = {"faces": {"up": {"gcode_sha256": "aa", "n": 1}}, "list": [1, [2, 3], {"k": 4}]}
    b = {"faces": {"up": {"gcode_sha256": "bb", "n": 1}}, "list": [1, [2, 9], {"k": 5}]}
    assert rr.json_diff_paths(a, b) == ["$.faces.up.gcode_sha256", "$.list[1][1]",
                                        "$.list[2].k"]


def test_missing_key_and_extra_list_items():
    assert rr.json_diff_paths({"a": 1, "b": 2}, {"a": 1, "c": 2}) == ["$.b", "$.c"]
    assert rr.json_diff_paths([1, 2], [1, 2, 3, 4]) == ["$[2]", "$[3]"]


def test_type_changes_are_differences():
    assert rr.json_diff_paths({"a": None}, {"a": {}}) == ["$.a"]
    assert rr.json_diff_paths({"a": [1]}, {"a": {"0": 1}}) == ["$.a"]
    assert rr.json_diff_paths(True, 1) == ["$"]
    assert rr.json_diff_paths(1, 1.0) == []          # equal JSON numbers
    assert rr.json_diff_paths(1, 1.5) == ["$"]


def test_generalize_replaces_indices():
    assert rr.generalize("$.list[12].a[0][3]") == "$.list[*].a[*][*]"


def test_compare_runs(tmp_path):
    a, b = tmp_path / "run-a", tmp_path / "run-b"
    for run, sha, line in ((a, "aa", "; time 1"), (b, "bb", "; time 2")):
        (run / "x").mkdir(parents=True)
        (run / "_logs").mkdir()
        (run / "_logs" / "step.txt").write_text(str(run))            # logs are left out
        (run / "same.bin").write_bytes(b"\x00\x01")
        (run / "x" / "rec.json").write_text(json.dumps({"id": "1", "gcode_sha256": sha}))
        (run / "x" / "plate_1.gcode").write_text(f"G1 X0\n{line}\nG1 X1\n")
        with zipfile.ZipFile(run / "m.3mf", "w") as z:
            z.writestr("same.xml", "<a/>")
            z.writestr("model.xml", sha)
    (a / "only.txt").write_text("a")
    out = rr.compare_runs(a, b)
    assert set(out) == {"same.bin", "x/rec.json", "x/plate_1.gcode", "m.3mf", "only.txt"}
    assert out["same.bin"]["identical"]
    assert out["x/rec.json"]["json_paths"] == ["$.gcode_sha256"]
    text = out["x/plate_1.gcode"]["text"]
    assert text["differing_lines"] == 1
    assert text["examples"] == [{"line": 2, "a": "; time 1", "b": "; time 2"}]
    assert out["m.3mf"]["zip"]["members_differ"] == ["model.xml"]
    assert out["only.txt"] == {"identical": False, "only_in": "run-a"}
    table = rr.volatile_table(out)
    assert table == [{"record": "rec.json", "path": "$.gcode_sha256",
                      "keys": ["gcode_sha256"], "files": ["x/rec.json"]}]


def test_same_json_value_different_bytes(tmp_path):
    (tmp_path / "a.json").write_text('{"a": 1}')
    (tmp_path / "b.json").write_text('{"a":1}')
    e = rr.compare_file(tmp_path / "a.json", tmp_path / "b.json")
    assert not e["identical"] and e["json_paths"] == []
    assert e["note"] == "same JSON value, different bytes"


def test_keys_with_dots_or_slashes_are_bracket_quoted():
    a = {"outputs": {"plate_1.gcode": "aa", "face-up/plate_1.gcode": "x", "k": [1]}}
    b = {"outputs": {"plate_1.gcode": "bb", "face-up/plate_1.gcode": "y", "k": [2]}}
    assert rr.json_diff_paths(a, b) == ['$.outputs["face-up/plate_1.gcode"]',
                                        "$.outputs.k[0]", '$.outputs["plate_1.gcode"]']
    assert rr.json_diff_keys(a, b)[0] == ("outputs", "face-up/plate_1.gcode")
    assert rr.render_path(("a[1]", 'q"', 3)) == '$["a[1]"]["q\\""][3]'


def test_unequal_line_counts_count_as_differing(tmp_path):
    t = rr._text_diff(b"a\nb\n", b"a\nb\nc\nd\n")
    assert t["differing_lines"] == 2 and t["line_counts_differ"]
    t = rr._text_diff(b"a\nx\n", b"a\ny\nz\n")
    assert t["differing_lines"] == 2 and t["line_counts_differ"]
    assert not rr._text_diff(b"a\nx\n", b"a\ny\n")["line_counts_differ"]


def test_gcode_timestamp_only(tmp_path):
    head = "; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.5.0 on 2026-11-16 at {}\n"
    a, b = tmp_path / "a.gcode", tmp_path / "b.gcode"
    a.write_text(head.format("15:11:34") + "; HEADER_BLOCK_END\nG1 X0\n")
    b.write_text(head.format("15:21:13") + "; HEADER_BLOCK_END\nG1 X0\n")
    e = rr.compare_file(a, b)
    assert e["gcode"] == {"timestamp_only": True, "normalised_equal": True}
    b.write_text(head.format("15:21:13") + "; HEADER_BLOCK_END\nG1 X1\n")
    assert rr.compare_file(a, b)["gcode"]["timestamp_only"] is False
    pa, pb = tmp_path / "prusaslicer.portability-only.gcode.txt", tmp_path / "p.gcode.txt"
    pa.write_text("; generated by PrusaSlicer 2.9.7 on 2026-11-16 at 20:11:42 UTC\nG1\n")
    pb.write_text("; generated by PrusaSlicer 2.9.7 on 2026-11-16 at 20:21:25 UTC\nG1\n")
    assert rr.compare_file(pa, pb)["gcode"] == {"timestamp_only": True,
                                                "normalised_equal": True}


def test_float_values_round_trip():
    assert rr.format_value(0.1 + 0.2) == "0.30000000000000004"
    assert float(rr.format_value(1234567.891)) == 1234567.891
    assert rr.format_value(30.0) == "30.0" and rr.format_value(128) == "128"
    assert rr._rule_or_flag({"rule": None, "value": 2.123456789}, "--x") == ["--x",
                                                                            "2.123456789"]
    assert rr._rule_or_flag({"rule": "r", "value": 2.5}, "--x") == []


def test_bad_record_is_a_plan_error(tmp_path):
    import pytest
    sel = tmp_path / "selection.json"
    sel.write_text(json.dumps({"controls": {"source": "controls"}}))     # no input
    with pytest.raises(rr.PlanError, match="selection.json"):
        rr.select_step("select/x", sel, tmp_path)
    sel.write_text("{not json")
    with pytest.raises(rr.PlanError, match="selection.json"):
        rr.select_step("select/x", sel, tmp_path)
    sel.write_text(json.dumps({"controls": {"source": "mask"}}))
    with pytest.raises(rr.PlanError, match="mask"):
        rr.select_step("select/x", sel, tmp_path)


def test_unknown_source_is_a_plan_error():
    import pytest
    with pytest.raises(rr.PlanError, match="unknown source"):
        rr.color_flags({"sources": {"edges": "magic"}, "settings": {"edges": "smooth"}},
                       "colors.json")
    assert rr.color_flags({"sources": {"edges": "flag", "colors": "profile"},
                           "settings": {"edges": "furry", "colors": 4}},
                          "colors.json") == ["--edges", "furry"]


def test_log_diff_one_side_only(tmp_path):
    a, b = tmp_path / "run-a", tmp_path / "run-b"
    for run in (a, b):
        (run / "_logs").mkdir(parents=True)
        (run / "_logs" / "s.txt").write_text(f"wrote {run}/x\nexit 0\n")
    (b / "_logs" / "extra.txt").write_text("exit 0\n")
    out = rr._log_diff(a, b)
    assert out["s.txt"] == {"identical": True}
    assert out["extra.txt"] == {"identical": False, "only_in": "run-b"}


def test_unexpected_exits_and_steps_without_files(tmp_path):
    steps = [rr.Step("select/a", []), rr.Step("slice/b", [], expect_exit={1})]
    runs = {"run-a": [{"step": "select/a", "exit": 0}, {"step": "slice/b", "exit": 1}],
            "run-b": [{"step": "select/a", "exit": 2}, {"step": "slice/b", "exit": 1}]}
    assert rr.unexpected_exits(steps, runs) == [
        {"step": "select/a", "recorded": [0], "run-a": 0, "run-b": 2}]
    (tmp_path / "run-a" / "select" / "a").mkdir(parents=True)
    (tmp_path / "run-a" / "select" / "a" / "f").write_text("x")
    (tmp_path / "run-b" / "slice" / "b").mkdir(parents=True)
    assert rr.steps_without_files(steps, tmp_path) == ["slice/b"]


def test_exits_read_back_from_logs(tmp_path):
    (tmp_path / "_logs").mkdir()
    (tmp_path / "_logs" / "select__a.txt").write_text("$ tdmg select\nout\n--- stderr\nexit 1\n")
    steps = [rr.Step("select/a", ["select"]), rr.Step("slice/b", ["slice"])]
    got = rr.runs_from_logs(steps, tmp_path)
    assert [g["exit"] for g in got] == [1, None]


def test_volatile_table_generalizes_indices_and_quotes_keys():
    files = {"s/slice.json": {"json_keys": [["outputs", "plate_1.gcode"], ["l", 3, "x"]]}}
    rows = rr.volatile_table(files)
    assert [(r["path"], r["keys"]) for r in rows] == [
        ('$.l[*].x', ["l", ["*"], "x"]), ('$.outputs["plate_1.gcode"]',
                                          ["outputs", "plate_1.gcode"])]
