"""The print-type model: four attributes, and the named recipes we implement.

A print job combines one value of each attribute. A recipe is a named combination
that the project implements. This registry is the single source of truth for the
recipe status table in docs/print-types/recipes.md (generated by scripts/gen_docs.py)
and, later, for which combinations the CLI accepts.
"""

from dataclasses import dataclass
from enum import Enum


class Geometry(str, Enum):
    G1 = "G1"  # flat / 2.5D extrusion: mask -> vector -> extrude
    G2 = "G2"  # relief / heightfield: grayscale or depth -> height grid
    G3 = "G3"  # full 3D: generative image-to-3D, then repair


class Articulation(str, Enum):
    A0 = "A0"  # none
    A1 = "A1"  # flat print-in-place joints (in-plane pin-in-loop hinges)
    A2 = "A2"  # 3D print-in-place joints (ball-and-socket, cone-pin)


class Color(str, Enum):
    C1 = "C1"  # single filament (any number of bodies)
    C2 = "C2"  # one body per filament, assigned in the 3MF
    C3 = "C3"  # per-triangle paint
    C4 = "C4"  # filament changes by layer


class Assembly(str, Enum):
    L1 = "L1"  # one print, one plate
    L2 = "L2"  # separately printed parts, assembled after printing


class Status(str, Enum):
    IMPLEMENTED = "implemented"
    PLANNED = "planned"
    NOT_PLANNED = "not planned"


ATTRIBUTE_LABELS: dict[str, str] = {
    "G1": "Flat / 2.5D extrusion",
    "G2": "Relief / heightfield",
    "G3": "Full 3D",
    "A0": "No joints",
    "A1": "Flat print-in-place joints",
    "A2": "3D print-in-place joints",
    "C1": "Single filament",
    "C2": "One body per filament",
    "C3": "Per-triangle paint",
    "C4": "Filament change by layer",
    "L1": "One print",
    "L2": "Parts assembled after printing",
}


@dataclass(frozen=True)
class Recipe:
    id: str
    name: str
    geometry: Geometry
    articulation: Articulation
    colors: tuple[Color, ...]
    assembly: Assembly
    example: str
    roadmap_phase: int
    status: Status = Status.PLANNED


RECIPES: tuple[Recipe, ...] = (
    Recipe("R1", "Flat single-color", Geometry.G1, Articulation.A0, (Color.C1,), Assembly.L1,
           "keychain, sign, cookie cutter", 1),
    Recipe("R2", "Flat multicolor", Geometry.G1, Articulation.A0, (Color.C2,), Assembly.L1,
           "two-color logo coaster", 3),
    Recipe("R3", "Relief and lithophane", Geometry.G2, Articulation.A0, (Color.C1, Color.C4),
           Assembly.L1, "lithophane, bas-relief", 4),
    Recipe("R4", "Figurine, single color", Geometry.G3, Articulation.A0, (Color.C1,), Assembly.L1,
           "figure from a photo", 5),
    Recipe("R5", "Assembled parts", Geometry.G3, Articulation.A0, (Color.C1,), Assembly.L2,
           "figure larger than the bed, or one color per part", 6),
    Recipe("R6", "Flat flexi", Geometry.G1, Articulation.A1, (Color.C1, Color.C2), Assembly.L1,
           "articulated flat animal", 7),
    Recipe("R7", "Painted figurine", Geometry.G3, Articulation.A0, (Color.C3,), Assembly.L1,
           "multicolor figure on AMS", 8),
    Recipe("R8", "3D flexi", Geometry.G3, Articulation.A2, (Color.C1,), Assembly.L1,
           "print-in-place articulated dragon (research track)", 9),
)


def recipe(recipe_id: str) -> Recipe:
    for r in RECIPES:
        if r.id == recipe_id:
            return r
    raise KeyError(f"unknown recipe {recipe_id!r}")
