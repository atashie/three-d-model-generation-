# Output classes: owner-facing names for groups of recipes, in recipe order. The order is
# policy: resolve() picks the first usable recipe that offers the requested color, so
# reordering a tuple can change which recipe a job gets.
CLASSES: dict[str, tuple[str, ...]] = {
    "flat-icon": ("R1", "R2"),
    "figurine": ("R4", "R7"),
    "flexi": ("R6", "R8"),
}


def recipe(recipe_id: str) -> Recipe:
    for r in RECIPES:
        if r.id == recipe_id:
            return r
    raise KeyError(f"unknown recipe {recipe_id!a}")


def class_of(recipe_id: str) -> str | None:
    """The output class a recipe belongs to, or None."""
    for name, ids in CLASSES.items():
        if recipe_id in ids:
            return name
    return None


def class_status(output_class: str) -> Status:
    """The best status among the class's recipes, in Status order."""
    order = list(Status)
    return min((recipe(i).status for i in CLASSES[output_class]), key=order.index)


def _offers(r: Recipe, colors: bool) -> bool:
    """True if `r` prints multicolor (colors) or single-color (not colors)."""
    if colors:
        return any(c is not Color.C1 for c in r.colors)
    return Color.C1 in r.colors


def resolve(output_class: str, colors: bool) -> Recipe:
    """The one recipe for a job of `output_class`, single-color or with `colors`.

    It takes the first recipe of the class, in CLASSES order, whose status is in USABLE
    and that offers C1 (colors False) or a color other than C1 (colors True). It refuses
    (ValueError) an unknown class, a class with no usable recipe, and a class with no
    usable recipe of the requested kind. Each refusal names the class and the status of
    its recipes."""
    if output_class not in CLASSES:
        raise ValueError(f"unknown output class {output_class!a} "
                         f"(known: {', '.join(CLASSES)})")
    members = [recipe(i) for i in CLASSES[output_class]]
    statuses = ", ".join(f"{r.id} {r.status.value}" for r in members)
    usable = [r for r in members if r.status in USABLE]
    if not usable:
        raise ValueError(f"output class {output_class!r} is "
                         f"{class_status(output_class).value}: no recipe in it is "
                         f"implemented or in progress ({statuses})")
    for r in usable:
        if _offers(r, colors):
            return r
    kind = "multicolor" if colors else "single-color"
    raise ValueError(f"output class {output_class!r} has no {kind} recipe that is "
                     f"implemented or in progress ({statuses})")
