"""OrcaSlicer as a pinned, hash-verified subprocess (docs/plans/2026-11-10-slicer-check.md).

The pin file `profiles/slicers/orcaslicer-2.5.0.yaml` records the release, the SHA-256
hashes of the zip, the exe, the main library, the whole app folder, the upstream profile
files and the flattened profiles, and the exit-code table. Its values come from
research/verification/2026-11-10-orcaslicer-windows/ (README.md and its addendum).

OrcaSlicer is AGPL-3.0. This module only runs it as a separate program; no OrcaSlicer code
or profile file is part of this repo.

Measured behaviour this module relies on (the research record):
- an open mesh slices with exit 0 into a truncated print, so F6.layer_count compares the
  layer count with the ones the model's thickness allows;
- on Windows the parent sees the exit code as an unsigned 32-bit value;
- `--logfile` writes a log on success only with `--debug` 2 or higher (addendum, item 1),
  so the log is optional;
- one STL loads as one object even when it holds several separate bodies (addendum,
  item 2), so F6.single_object cannot count bodies. F4.body_count does that before the
  slicer runs; it is UNKNOWN for several bodies, which still blocks certification.
"""

from __future__ import annotations

import hashlib
import json
import math
import os
import re
import signal
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Annotated, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, StringConstraints, model_validator

from tdmg.checks import CheckResult
from tdmg.paths import PROFILES_DIR

PIN_ID = "orcaslicer-2.5.0"
PROFILE_KINDS = ("machine", "process", "filament")
ENV_VAR = "TDMG_ORCASLICER_DIR"
GCODE_NAME = "plate_1.gcode"            # what --slice 0 wrote for a one-plate STL (measured)
STATS_NAME = "plate_1.statistics.json"  # what --export-statistics wrote (measured)
TIMEOUT_RULE = "slicer.orca.timeout_s"
# The statistics units the parsed values are reported in; other units are refused.
STATS_UNITS = {"time": "s", "volume": "mm3", "weight": "g"}
# The G-code line that differed between two otherwise identical runs (research record,
# finding 7): "; generated by OrcaSlicer 2.5.0 on <date> at <time>". It is looked for only
# between these two header lines, where the real G-code has it (line 2 of 11).
GENERATED_LINE = re.compile(rb"^; generated by .* at .*$")
HEADER_START, HEADER_END = b"; HEADER_BLOCK_START", b"; HEADER_BLOCK_END"
# How far (t - first) / h may be from x.5 and still count as half a layer. An
# arithmetic margin, not a physical tolerance: float error in that quotient is about 1e-15,
# and 1e-6 of a 0.2 mm layer is 0.2 nm, far below any thickness a user would ask for.
HALF_LAYER_TOL = 1e-6
# Display only: how much of the slicer's stdout and stderr a run keeps (the end of each).
OUTPUT_TAIL_CHARS = 4000
# After killing a timed-out slicer, how long to wait for its pipes to close. Not a design
# number: a bound on cleanup, so a process that escaped the kill cannot hang tdmg.
KILL_WAIT_S = 10
_CHUNK = 1 << 20

Sha256 = Annotated[str, StringConstraints(pattern=r"^[0-9a-f]{64}$")]


class SlicerError(ValueError):
    """The slicer cannot be used as asked: missing, changed, or misconfigured."""


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class Release(_Model):
    platform: Literal["windows-x64"]
    asset: str
    url: str
    sha256: Sha256


class PinnedFile(_Model):
    path: str = Field(description="Relative to the slicer folder")
    sha256: Sha256


Exe = PinnedFile


class AppTree(_Model):
    folder: str = Field(description="Relative to the slicer folder")
    files: int = Field(ge=1)
    sha256: Sha256


class FlatProfile(_Model):
    file: str
    preset: str
    chain: list[str] = Field(min_length=1, description="Inheritance chain, root first")
    includes: list[str] = Field(
        default_factory=list,
        description="Template presets named by the chain's include keys, root first, each "
                    "preset's in the order listed")
    sha256: Sha256

    @model_validator(mode="after")
    def _leaf_last(self) -> FlatProfile:
        if self.chain[-1] != self.preset:
            raise ValueError(f"{self.file}: the chain must end with the preset {self.preset!r}")
        return self


class Profiles(_Model):
    folder: str = Field(description="Relative to the slicer folder")
    source_base: str
    vendor: str
    drop_keys: list[str]
    flat: dict[Literal["machine", "process", "filament"], FlatProfile]
    manifest_sha256: Sha256
    upstream_sha256: dict[str, Sha256] = Field(min_length=1)
    include_defaults_sha256: dict[str, Sha256] = Field(
        default_factory=dict,
        description="SHA-256 of OrcaSlicer's default for each setting an included template "
                    "sets; a template value equal to it is refused")

    @model_validator(mode="after")
    def _all_kinds(self) -> Profiles:
        if set(self.flat) != set(PROFILE_KINDS):
            raise ValueError(f"flat profiles must be exactly {PROFILE_KINDS}")
        return self


class Decoding(_Model):
    rule: Literal["unsigned32", "low8"]
    status: Literal["measured", "assumed"]
    source: str


class SlicerPin(_Model):
    id: str
    name: str
    version: str
    tag: str
    licence: str
    record: str
    release: Release
    exe: PinnedFile
    libraries: list[PinnedFile] = Field(min_length=1)
    app_tree: AppTree
    profiles: Profiles
    decoding: dict[Literal["windows", "posix"], Decoding]
    exit_codes_source: str
    exit_codes: dict[int, str]

    @model_validator(mode="after")
    def _check(self) -> SlicerPin:
        if set(self.decoding) != {"windows", "posix"}:
            raise ValueError(f"{self.id}: decoding needs both 'windows' and 'posix'")
        if self.exit_codes.get(0) != "CLI_SUCCESS":
            raise ValueError(f"{self.id}: exit code 0 must be CLI_SUCCESS")
        prefix = self.app_tree.folder + "/"
        if not all(f.path.startswith(prefix) for f in (self.exe, *self.libraries)):
            raise ValueError(f"{self.id}: the exe and libraries must be inside {prefix}")
        return self


def load_pin(pin_id: str = PIN_ID, profiles_dir: Path = PROFILES_DIR) -> SlicerPin:
    path = profiles_dir / "slicers" / f"{pin_id}.yaml"
    return SlicerPin.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))


def sha256_file(path: str | Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(_CHUNK):
            digest.update(chunk)
    return digest.hexdigest()


def app_tree_sha256(folder: str | Path) -> tuple[int, str]:
    """(file count, tree hash) of every file under folder.

    The tree hash is the SHA-256 of the UTF-8 lines "<relative path with />\\t<sha256>\\n",
    sorted as Python strings (the pin file; app_tree_hash.py in the research record).
    """
    root = Path(folder)
    lines = sorted(f"{p.relative_to(root).as_posix()}\t{sha256_file(p)}"
                   for p in root.rglob("*") if p.is_file())
    tree = hashlib.sha256("".join(line + "\n" for line in lines).encode("utf-8"))
    return len(lines), tree.hexdigest()


SETUP_SCRIPT = "scripts/setup_orcaslicer.py"


def _verified(path: Path, expected: str, setup_script: str = SETUP_SCRIPT) -> str:
    if not path.is_file():
        raise SlicerError(f"{path} is missing; run {setup_script}")
    actual = sha256_file(path)
    if actual != expected:
        raise SlicerError(f"{path} has sha256 {actual}, which does not match the pin "
                          f"({expected}); reinstall with {setup_script}")
    return actual


def verify_tree(slicer_dir: str | Path, pin, setup_script: str = SETUP_SCRIPT) -> dict:
    """{files, sha256} of the pin's app folder, checked against the pin. SlicerError if not."""
    folder = Path(slicer_dir) / pin.app_tree.folder
    files, tree = app_tree_sha256(folder)
    if (files, tree) != (pin.app_tree.files, pin.app_tree.sha256):
        raise SlicerError(
            f"app tree {folder} ({files} files, sha256 {tree}) does not match the pin "
            f"({pin.app_tree.files} files, {pin.app_tree.sha256}); reinstall with "
            f"{setup_script}")
    return {"files": files, "sha256": tree}


def verify_app(slicer_dir: str | Path, pin, setup_script: str = SETUP_SCRIPT) -> dict:
    """{exe_sha256, libraries: {path: sha256}}: the pin's exe and libraries, checked.

    pin is any pin with exe, libraries and app_tree (SlicerPin, or PrusaPin in
    tdmg.portability). Raises SlicerError naming setup_script.
    """
    root = Path(slicer_dir)
    return {"exe_sha256": _verified(root / pin.exe.path, pin.exe.sha256, setup_script),
            "libraries": {lib.path: _verified(root / lib.path, lib.sha256, setup_script)
                          for lib in pin.libraries}}


def verify_install(slicer_dir: str | Path, pin: SlicerPin, full_tree: bool = False) -> dict:
    """Check the exe, the libraries and the three flattened profiles against the pin.

    full_tree also checks every file under the app folder (the setup script and
    --verify-only do; locate does not, to keep each run quick). Raises SlicerError.
    Returns {exe_sha256, libraries: {path: sha256}, profiles: {kind: {name, file, sha256}}},
    plus app_tree: {files, sha256} when full_tree.
    """
    root = Path(slicer_dir)
    found = verify_app(root, pin)
    profiles = {}
    for kind in PROFILE_KINDS:
        p = pin.profiles.flat[kind]
        profiles[kind] = {"name": p.preset, "file": p.file,
                          "sha256": _verified(root / pin.profiles.folder / p.file, p.sha256)}
    found["profiles"] = profiles
    if full_tree:
        found["app_tree"] = verify_tree(root, pin)
    return found


# --- Locating and running ------------------------------------------------------------


@dataclass(frozen=True)
class Slicer:
    """A verified install: the exe, the three flattened profiles, and their hashes."""
    root: Path
    exe: Path
    profiles: dict[str, Path]
    verified: dict
    pin: SlicerPin


def locate(slicer_dir: str | Path | None, pin: SlicerPin | None = None,
           full_tree: bool = True) -> Slicer:
    """The install in slicer_dir, else in $TDMG_ORCASLICER_DIR, verified against the pin.

    Checks the exe, the libraries and the profiles, and with full_tree (the default) every
    file of the app tree: about 2.6 s for the 4,054 files on the owner's PC, measured
    2026-11-10. Never searches the system: an unpinned OrcaSlicer must not be used by
    accident.
    """
    pin = pin or load_pin()
    folder = slicer_dir if slicer_dir is not None else os.environ.get(ENV_VAR)
    if not folder:
        raise SlicerError(f"no slicer folder: pass --slicer-dir DIR or set {ENV_VAR}; install "
                          "one with `uv run python scripts/setup_orcaslicer.py --dest DIR`")
    root = Path(folder).resolve()
    if not root.is_dir():
        raise SlicerError(f"slicer folder {root} is not a folder; install one with "
                          "`uv run python scripts/setup_orcaslicer.py --dest DIR`")
    verified = verify_install(root, pin, full_tree=full_tree)
    profiles = {k: root / pin.profiles.folder / pin.profiles.flat[k].file for k in PROFILE_KINDS}
    return Slicer(root, root / pin.exe.path, profiles, verified, pin)


def slicer_args(stl: Path, profiles: dict[str, Path], out_dir: Path, log: Path) -> list[str]:
    """The arguments after the program, exactly in the measured form (research record)."""
    return [str(stl), "--load-settings", f"{profiles['machine']};{profiles['process']}",
            "--load-filaments", str(profiles["filament"]), "--slice", "0",
            "--outputdir", str(out_dir), "--export-statistics", "--logfile", str(log)]


@dataclass(frozen=True)
class SlicerRun:
    args: list[str]
    returncode: int | None   # None when the run was stopped at the timeout
    timed_out: bool
    timeout_s: float
    stdout: str              # the last OUTPUT_TAIL_CHARS characters
    stderr: str              # the last OUTPUT_TAIL_CHARS characters
    out_dir: Path
    log_path: Path           # often absent: written on success only with --debug (measured)


def run_slicer(cmd_prefix: list[str], stl: Path, profiles: dict[str, Path], workdir: Path,
               timeout: float) -> SlicerRun:
    """Run the slicer on one STL in an empty workdir: outputs in workdir/out, log beside it.

    cmd_prefix is [exe] for OrcaSlicer, or [sys.executable, fake.py] in tests; its program
    must be an absolute path, since the run's working folder is workdir. A run still going
    after `timeout` seconds is killed with every process it started, and reported with
    timed_out=True.
    """
    if not Path(cmd_prefix[0]).is_absolute():
        raise SlicerError(f"the slicer program {cmd_prefix[0]} must be an absolute path")
    work = Path(workdir).resolve()
    if not work.is_dir() or any(work.iterdir()):
        raise SlicerError(f"slicer work folder {work} must be an existing, empty folder")
    absolute = {k: Path(v).resolve() for k, v in profiles.items()}
    for kind in ("machine", "process"):
        if ";" in str(absolute[kind]):     # --load-settings separates its two paths with ";"
            raise SlicerError(f"the {kind} profile path {absolute[kind]} contains ';', which "
                              "--load-settings cannot take")
    out_dir, log = work / "out", work / "slicer.log"
    out_dir.mkdir()
    args = [*cmd_prefix, *slicer_args(Path(stl).resolve(), absolute, out_dir, log)]
    returncode, timed_out, out, err = run_process(args, work, timeout)
    return SlicerRun(args, returncode, timed_out, timeout, output_tail(out), output_tail(err),
                     out_dir, log)


def run_process(args: list[str], cwd: Path,
                timeout: float) -> tuple[int | None, bool, bytes, bytes]:
    """(returncode, timed_out, stdout, stderr) of one run of args in cwd.

    A run still going after `timeout` seconds is killed with every process it started;
    its returncode is then None. Used for OrcaSlicer and PrusaSlicer (tdmg.portability).
    """
    # A new process group on POSIX, so a timeout can kill everything the slicer started.
    group = {} if os.name == "nt" else {"start_new_session": True}
    try:
        proc = subprocess.Popen(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                stdin=subprocess.DEVNULL, cwd=cwd, **group)
    except OSError as err:
        raise SlicerError(f"cannot start the slicer {args[0]}: {err}") from err
    timed_out = False
    try:
        out, err = proc.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        _kill_tree(proc)
        try:
            out, err = proc.communicate(timeout=KILL_WAIT_S)
        except subprocess.TimeoutExpired:
            proc.kill()
            out, err = b"", b""
    return None if timed_out else proc.returncode, timed_out, out or b"", err or b""


def _kill_tree(proc: subprocess.Popen) -> None:
    """Kill proc and every process it started: taskkill /T on Windows, the group on POSIX."""
    if os.name == "nt":
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(proc.pid)],
                       capture_output=True, check=False)
    else:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
    proc.kill()   # in case the tree kill missed it; harmless if it is already gone


def output_tail(data: bytes | None) -> str:
    """The last OUTPUT_TAIL_CHARS characters of a run's output, decoded as UTF-8."""
    return (data or b"").decode("utf-8", errors="replace")[-OUTPUT_TAIL_CHARS:]


# --- Exit codes ----------------------------------------------------------------------


def platform_key() -> Literal["windows", "posix"]:
    return "windows" if sys.platform == "win32" else "posix"


def decode_exit(raw: int, platform: str, pin: SlicerPin | None = None) -> dict:
    """{raw, signed, name, decoding} for a return code as the parent process saw it.

    windows: the full 32-bit code as an unsigned value (measured, research record).
    posix: the low 8 bits, so 128-255 are negative codes (assumed from the M5 notes in
    CLAUDE.md; not measured for 2.5.0). A negative raw value on POSIX means the process
    was killed by that signal. name is None for a code the v2.5.0 table does not list.
    """
    pin = pin or load_pin()
    if platform not in pin.decoding:
        raise SlicerError(f"unknown platform {platform!r}; expected 'windows' or 'posix'")
    rule = pin.decoding[platform]
    decoding = {"platform": platform, "rule": rule.rule, "status": rule.status,
                "source": rule.source}
    if rule.rule == "unsigned32":
        if not 0 <= raw < 2**32:
            raise SlicerError(f"exit code {raw} is out of range for an unsigned 32-bit value")
        signed = raw - 2**32 if raw >= 2**31 else raw
    else:
        if raw < 0:
            return {"raw": raw, "signed": None, "name": f"killed by signal {-raw}",
                    "decoding": decoding}
        if raw > 255:
            raise SlicerError(f"exit code {raw} is out of range for an 8-bit value")
        signed = raw - 256 if raw > 127 else raw
    return {"raw": raw, "signed": signed, "name": pin.exit_codes.get(signed),
            "decoding": decoding}


# --- Outputs -------------------------------------------------------------------------


def _height(process: dict, key: str) -> float:
    if key not in process:
        raise SlicerError(f"process profile has no {key!r}")
    value = process[key]
    try:
        height = float(value)
    except (TypeError, ValueError):
        raise SlicerError(f"process profile {key!r} is {value!r}, not a number") from None
    if not (math.isfinite(height) and height > 0):
        raise SlicerError(f"process profile {key!r} must be positive, not {value!r}")
    return height


def expected_layer_counts(thickness_mm: float, process_profile: dict,
                          storage_error_mm: float = 0.0) -> set[int]:
    """The layer counts OrcaSlicer may produce for a part of this thickness.

    With q = (thickness - initial_layer_print_height) / layer_height, both heights from the
    flattened process profile: {1 + round(q)}, or both neighbours {1 + floor(q), 2 + floor(q)}
    when q is within storage_error_mm / layer_height + HALF_LAYER_TOL of x.5.
    storage_error_mm bounds how far the stored thickness may be from the one the slicer
    reads (tdmg.slicing derives it for float32 STL). Measured on OrcaSlicer 2.5.0 with 0.2/0.2 mm
    (research README, addendum item 3): 20 mm gave 100 and 3.0 mm 15; away from a half layer
    it matched the nearest count (3.05 -> 15, 3.15 -> 16); at exactly half a layer it went
    either way (1.1 -> 6, 0.3 -> 2, but 2.1 -> 10, 3.1 -> 15, 0.5 -> 2).
    """
    first = _height(process_profile, "initial_layer_print_height")
    layer = _height(process_profile, "layer_height")
    thickness = float(thickness_mm)
    if not math.isfinite(thickness) or thickness < first:
        raise SlicerError(f"thickness {thickness_mm} mm is thinner than the first layer "
                          f"({first} mm)")
    if not (math.isfinite(storage_error_mm) and storage_error_mm >= 0):
        raise SlicerError(f"storage_error_mm must be finite and >= 0, not {storage_error_mm}")
    q = (thickness - first) / layer
    whole = math.floor(q)
    if abs(q - whole - 0.5) <= storage_error_mm / layer + HALF_LAYER_TOL:
        return {1 + whole, 2 + whole}
    return {1 + round(q)}


def parse_statistics(path: Path) -> dict:
    """The summary facts from plate_N.statistics.json; SlicerError if it cannot be read."""
    path = Path(path)
    try:
        data = json.loads(path.read_bytes())
    except (OSError, ValueError) as err:
        raise SlicerError(f"cannot read slicer statistics {path}: {err}") from err
    units = data.get("units", {}) if isinstance(data, dict) else {}
    if any(units.get(k) != v for k, v in STATS_UNITS.items()):
        raise SlicerError(f"{path}: statistics units {units} are not {STATS_UNITS}")
    summary = data.get("summary", {})
    try:
        layers = summary["layer_count"]
        facts = {"time_s": float(summary["time"]), "volume_mm3": float(summary["volume"]),
                 "weight_g": float(summary["weight"])}
        objects = [str(o["name"]) for o in data["objects"]]
    except (KeyError, TypeError, ValueError) as err:
        raise SlicerError(f"{path}: statistics lack {err} (need summary.layer_count, time, "
                          "volume, weight and objects[].name)") from err
    if not isinstance(layers, int) or isinstance(layers, bool):
        raise SlicerError(f"{path}: summary.layer_count is {layers!r}, not an integer")
    return {"generator": data.get("generator"), "layer_count": layers, **facts,
            "objects": objects}


def gcode_hashes(data: bytes) -> dict:
    """The raw SHA-256, and one with the "; generated by ... at ..." header line blanked.

    That line carries the run's date and time; it was the only difference between two runs
    (research record). Only the first such line between HEADER_BLOCK_START and
    HEADER_BLOCK_END is blanked, keeping its line end, so any other change shows. Without a
    complete header block nothing is blanked.
    """
    lines = data.split(b"\n")
    bare = [line.rstrip(b"\r") for line in lines]
    blanked = 0
    if HEADER_START in bare:
        start = bare.index(HEADER_START)
        end = next((i for i in range(start + 1, len(bare)) if bare[i] == HEADER_END), None)
        for i in range(start + 1, end if end is not None else start + 1):
            if GENERATED_LINE.match(bare[i]):
                lines[i] = b"\r" if lines[i].endswith(b"\r") else b""
                blanked = 1
                break
    return {"sha256": hashlib.sha256(data).hexdigest(),
            "normalised_sha256": hashlib.sha256(b"\n".join(lines)).hexdigest(),
            "normalised_lines": blanked}


# --- F6 checks -----------------------------------------------------------------------


def f6_checks(run: SlicerRun, expected_counts: set[int] | frozenset[int],
              pin: SlicerPin | None = None,
              timeout_rule: str | None = TIMEOUT_RULE) -> tuple[list[CheckResult], dict | None]:
    """F6 on a run's outputs, and the parsed statistics (None when there are none).

    timeout_rule is the rule that set run.timeout_s, named by F6.slicer_exit when the run
    was stopped; None when the caller chose the timeout explicitly.

    expected_counts is expected_layer_counts(...); the check records it as a sorted list.
    After a failed or stopped run, a missing statistics file leaves layer_count and
    single_object UNKNOWN; after a clean exit it is a FAIL, because it was asked for.
    """
    pin = pin or load_pin()
    allowed = sorted(expected_counts)
    checks = [_exit_check(run, pin, timeout_rule)]
    exited_ok = checks[0].status == "PASS"

    gcode = run.out_dir / GCODE_NAME
    size = gcode.stat().st_size if gcode.is_file() else None
    checks.append(CheckResult(
        "F6.gcode_present", "PASS" if size else "FAIL", {"file": GCODE_NAME, "bytes": size},
        None, None, "" if size else f"{GCODE_NAME} was not written" if size is None
        else f"{GCODE_NAME} is empty"))

    stats_path = run.out_dir / STATS_NAME
    stats, problem = None, ""
    if stats_path.is_file():
        try:
            stats = parse_statistics(stats_path)
        except SlicerError as err:
            problem = str(err)
    else:
        problem = f"{STATS_NAME} was not written"
    if stats is None:
        status = "FAIL" if exited_ok else "UNKNOWN"
        why = problem if exited_ok else f"not measured: the slicer failed ({problem})"
        checks += [CheckResult("F6.layer_count", status, None, allowed, None,
                               f"no statistics: {why}"),
                   CheckResult("F6.single_object", status, None, 1, None,
                               f"no statistics: {why}")]
    else:
        actual = stats["layer_count"]
        ok = actual in expected_counts
        checks.append(CheckResult(
            "F6.layer_count", "PASS" if ok else "FAIL", actual, allowed, None,
            "allowed = 1 + round((thickness - initial_layer_print_height) / layer_height), "
            "or either neighbour at exactly half a layer"
            + ("" if ok else
               f"; the slicer made {actual} layers, not {allowed}: the print's height is "
               "wrong, as when an open mesh slices into too few layers. This catches height "
               "truncation only; F1 is the guard for other mesh defects")))
        n = len(stats["objects"])
        checks.append(CheckResult(
            "F6.single_object", "PASS" if n == 1 else "FAIL", n, 1, None,
            "objects in the slicer statistics; one STL loads as one object even with "
            "several bodies, which F4.body_count checks (UNKNOWN for several bodies, which "
            "blocks certification)"))
    return checks, stats


def _exit_check(run: SlicerRun, pin: SlicerPin, timeout_rule: str | None) -> CheckResult:
    if run.timed_out:
        return CheckResult("F6.slicer_exit", "FAIL", None, run.timeout_s, timeout_rule,
                           f"stopped after the {run.timeout_s:g} s timeout")
    code = decode_exit(run.returncode, platform_key(), pin)
    if code["signed"] == 0:
        return CheckResult("F6.slicer_exit", "PASS", code, 0, None, "exit 0 (CLI_SUCCESS)")
    detail = run.stderr.strip().splitlines()[-1] if run.stderr.strip() else ""
    name = code["name"] or "a code the v2.5.0 table does not list"
    shown = code["signed"] if code["signed"] is not None else code["raw"]
    return CheckResult("F6.slicer_exit", "FAIL", code, 0, None,
                       f"exit {shown} ({name})" + (f": {detail}" if detail else ""))
