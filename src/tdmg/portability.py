"""PrusaSlicer 2.9.7 as a pinned, hash-verified subprocess for F6.portability.

docs/plans/2026-11-11-portability-check.md. The pin file
`profiles/slicers/prusaslicer-2.9.7.yaml` records the release, the SHA-256 hashes of the
zip, the console exe, PrusaSlicer.dll and the whole app folder, and how exit codes are
read. Its values come from research/verification/2026-11-11-prusaslicer-windows/.

PrusaSlicer is AGPL-3.0. This module only runs it as a separate program; no PrusaSlicer
code or profile file is part of this repo. Where a docstring says what PrusaSlicer does
inside, it was read in its source at tag version_2.9.7 on 2026-11-11 (file and function
named), and only the fact is restated here.

What F6.portability shows for STL, and what it does not: a second slicer (PrusaSlicer
2.9.7) accepts model.stl as modelled (its admesh read agrees with tdmg's trimesh read:
parts, facets, sizes, volume) and slices its full height, with extrusion on every layer,
given the A1 bed, nozzle, layer and filament settings. Its other settings are PrusaSlicer's
defaults, so this is not the A1 print process (for example 20% infill and Arachne
perimeters against the profile's 15% and classic). It does not show that every layer is
fully printed; F3 judges that for the OrcaSlicer G-code. OrcaSlicer and PrusaSlicer share
the admesh STL reader, so for STL this is not a check by an independent reader; a 3MF
output must re-run portability with truly different readers.

PrusaSlicer is located only from --prusaslicer-dir or $TDMG_PRUSASLICER_DIR, never by
searching the system, so an unpinned PrusaSlicer is never used by accident. When neither
is given, locate_prusaslicer returns None and F6.portability stays UNKNOWN.

Measured behaviour this module relies on (the research record):
- errors exit 1, and exit 0 is not success: a part outside the bed exits 0 with no G-code,
  and an open mesh exits 0 with a truncated G-code, so the outputs are read;
- `--info` prints one "[file]" line, then "key = value" lines;
- the G-code marks each layer with ";LAYER_CHANGE" and its top with ";Z:";
- two runs on one STL differ only in G-code line 1, "; generated by PrusaSlicer 2.9.7 on
  <date> at <time> UTC".
"""

