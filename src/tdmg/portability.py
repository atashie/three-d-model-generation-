class PrusaDecoding(_Model):
    error_exit: int      # the code every measured error exited with
    status: Literal["measured", "assumed"]
    source: str


class PrusaPin(_Model):
    """The pinned PrusaSlicer. Unlike the OrcaSlicer pin it has no profiles (no vendor
    profile is used) and no exit-code table (errors exit 1, measured)."""
    id: str
    name: str
    version: str
    tag: str
    licence: str
    record: str
    release: Release
    exe: PinnedFile
    libraries: list[PinnedFile] = Field(min_length=1)
    app_tree: AppTree
    decoding: dict[Literal["windows"], PrusaDecoding]

    @model_validator(mode="after")
    def _check(self) -> PrusaPin:
        prefix = self.app_tree.folder + "/"
        if not all(f.path.startswith(prefix) for f in (self.exe, *self.libraries)):
            raise ValueError(f"{self.id}: the exe and libraries must be inside {prefix}")
        return self


def load_prusa_pin(pin_id: str = PRUSA_PIN_ID, profiles_dir: Path = PROFILES_DIR) -> PrusaPin:
    path = profiles_dir / "slicers" / f"{pin_id}.yaml"
    return PrusaPin.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))


def verify_prusa_install(prusa_dir: str | Path, pin: PrusaPin,
                         full_tree: bool = False) -> dict:
    """Check the exe and PrusaSlicer.dll, and with full_tree every file under app/.

    Returns {exe_sha256, libraries: {path: sha256}}, plus app_tree: {files, sha256} when
    full_tree. Raises SlicerError, naming the setup script.
    """
    found = verify_app(prusa_dir, pin, PRUSA_SETUP_SCRIPT)
    if full_tree:
        found["app_tree"] = verify_tree(prusa_dir, pin, PRUSA_SETUP_SCRIPT)
    return found


@dataclass(frozen=True)
class PrusaSlicer:
    """A verified PrusaSlicer install: the console exe and the hashes checked."""
    root: Path
    exe: Path
    verified: dict
    pin: PrusaPin

    def identity(self) -> dict:
        """What slice_id records of this install: as for OrcaSlicer, the pinned tree hash
        and whether this run verified it."""
        return {"version": self.pin.version, "exe_sha256": self.verified["exe_sha256"],
                "libraries": self.verified["libraries"],
                "app_tree_sha256": self.pin.app_tree.sha256,
                "app_tree_verified": "app_tree" in self.verified}


def locate_prusaslicer(prusa_dir: str | Path | None, pin: PrusaPin | None = None,
                       full_tree: bool = True) -> PrusaSlicer | None:
    """The install in prusa_dir, else in $TDMG_PRUSASLICER_DIR, verified against the pin.

    None when neither is given: PrusaSlicer is optional, and F6.portability is then
    UNKNOWN. A folder that is given but missing or unverified raises SlicerError, as for
    OrcaSlicer. full_tree (the default) hashes every file of the app folder: for the 1,119
    files on the owner's PC, about 2 s with the files cached and 11 s on a first, cold read
    (2026-11-11).
    """
    pin = pin or load_prusa_pin()
    folder = prusa_dir if prusa_dir is not None else os.environ.get(PRUSA_ENV_VAR)
    if not folder:
        return None
    root = Path(folder).resolve()
    if not root.is_dir():
        raise SlicerError(f"PrusaSlicer folder {root} is not a folder; install one with "
                          f"`uv run python {PRUSA_SETUP_SCRIPT} --dest DIR`")
    verified = verify_prusa_install(root, pin, full_tree=full_tree)
    return PrusaSlicer(root, root / pin.exe.path, verified, pin)


# --- Settings and commands -------------------------------------------------------------


def _positive(value, where: str) -> str:
    """A positive finite number as its profile string; one-item lists are unwrapped."""
    if isinstance(value, list):
        if len(value) != 1:
            raise SlicerError(f"{where} must hold one value, not {value!r}")
        value = value[0]
    if not isinstance(value, str):
        raise SlicerError(f"{where} is {value!r}, not a number string")
    try:
        number = float(value)
    except ValueError:
        raise SlicerError(f"{where} is {value!r}, not a number") from None
    if not (math.isfinite(number) and number > 0):
        raise SlicerError(f"{where} must be positive and finite, not {value!r}")
    return value


def _bed_shape(value, where: str) -> str:
    if not isinstance(value, list) or len(value) < 3:
        raise SlicerError(f"{where} must be a list of at least 3 'XxY' corners, not {value!r}")
    for corner in value:
        parts = corner.split("x") if isinstance(corner, str) else []
        try:
            ok = len(parts) == 2 and all(math.isfinite(float(p)) for p in parts)
        except ValueError:
            ok = False
        if not ok:
            raise SlicerError(f"{where} has a corner {corner!r} that is not 'XxY'")
    return ",".join(value)


def explicit_settings(machine: dict, process: dict, filament: dict) -> dict[str, dict]:
    """{option: {value, profile, key}} for every PrusaSlicer setting, in SETTINGS order.

    Each value is the profile's own string (a one-item list unwrapped; printable_area's
    corners joined with ","), checked to be a positive finite number (corners: finite).
    A missing or unreadable value raises SlicerError: the run is refused.
    """
    profiles = {"machine": machine, "process": process, "filament": filament}
    out = {}
    for option, kind, key in SETTINGS:
        profile = profiles[kind]
        where = f"{kind} profile {key!r} (for {option})"
        if not isinstance(profile, dict) or profile.get(key) is None:
            raise SlicerError(f"{kind} profile has no {key!r} for {option}")
        value = (_bed_shape(profile[key], where) if key == "printable_area"
                 else _positive(profile[key], where))
        out[option] = {"value": value, "profile": kind, "key": key}
    return out


def info_args(stl: Path) -> list[str]:
    """`--info MODEL.stl`, the measured form."""
    return ["--info", str(stl)]


def gcode_args(stl: Path, gcode: Path, settings: dict[str, dict]) -> list[str]:
    """`--export-gcode MODEL.stl -o OUT.gcode` and the settings, the measured form."""
    args = ["--export-gcode", str(stl), "-o", str(gcode)]
    for option, setting in settings.items():
        args += [option, setting["value"]]
    return args


def command_templates(settings: dict[str, dict],
                      model: str = "<model.stl>") -> dict[str, list[str]]:
    """Both commands as recorded: placeholders, so the record holds no path. model is the
    model's placeholder ("<model.3mf>" for tdmg.color_slicing)."""
    exe = "<prusa-slicer-console.exe>"
    return {"info": [exe, *info_args(Path(model))],
            "gcode": [exe, *gcode_args(Path(model), Path(f"<{PRUSA_GCODE_NAME}>"),
                                       settings)]}


# --- Running -----------------------------------------------------------------------------


@dataclass(frozen=True)
class PrusaRun:
    returncode: int | None   # None when the run was stopped at the timeout
    timed_out: bool
    timeout_s: float
    stdout: str              # all of it: --info is parsed from it
    stderr: str              # the last OUTPUT_TAIL_CHARS characters

    def summary(self) -> dict:
        return {"returncode": self.returncode, "timed_out": self.timed_out,
                "stdout_tail": self.stdout[-OUTPUT_TAIL_CHARS:], "stderr_tail": self.stderr}


def _run(cmd_prefix: list[str], args: list[str], work: Path, timeout: float,
         hide: dict[str, str]) -> PrusaRun:
    """One run in the new folder work. Each path in hide is replaced by its placeholder in
    the whole output, before the tail is cut, so the record holds no path from this machine
    and no part of one (PrusaSlicer prints the G-code's full path)."""
    work.mkdir()
    returncode, timed_out, out, err = run_process([*cmd_prefix, *args], work, timeout)
    text = out.decode("utf-8", errors="replace")
    errors = err.decode("utf-8", errors="replace")
    for path, placeholder in sorted(hide.items(), key=lambda kv: -len(kv[0])):
        text, errors = text.replace(path, placeholder), errors.replace(path, placeholder)
    return PrusaRun(returncode, timed_out, timeout, text, errors[-OUTPUT_TAIL_CHARS:])


def run_portability(cmd_prefix: list[str], stl: Path, settings: dict[str, dict],
                    workdir: Path, timeout: float, prusa: PrusaSlicer | None = None,
                    placeholder: str = "<model.stl>",
                    ) -> tuple[PrusaRun, PrusaRun, bytes | None]:
    """Run --info and then --export-gcode on stl, each in its own new folder in workdir.

    cmd_prefix is [exe], or [sys.executable, fake_prusa.py] in tests; its program must be
    an absolute path. Each run gets the full timeout. The work folder, the model, the
    program and, when given, the install's folder and exe are hidden in the output kept
    (the model as placeholder). The model may be a 3MF (tdmg.color_slicing). Returns
    both runs and the G-code's bytes (None when none was written).
    """
    if not Path(cmd_prefix[0]).is_absolute():
        raise SlicerError(f"the PrusaSlicer program {cmd_prefix[0]} must be an absolute path")
    work = Path(workdir).resolve()
    if not work.is_dir() or any(work.iterdir()):
        raise SlicerError(f"PrusaSlicer work folder {work} must be an existing, empty folder")
    model = Path(stl).resolve()
    hide = {str(work): "<work>", str(model): placeholder,
            str(Path(cmd_prefix[0])): "<prusa-slicer-console.exe>"}
    if prusa is not None:
        hide |= {str(prusa.root): "<prusaslicer-dir>",
                 str(prusa.exe): "<prusa-slicer-console.exe>"}
    info = _run(cmd_prefix, info_args(model), work / "info", timeout, hide)
    gcode_path = work / "gcode" / PRUSA_GCODE_NAME
    gcode_run = _run(cmd_prefix, gcode_args(model, gcode_path, settings), work / "gcode",
                     timeout, hide)
    gcode = gcode_path.read_bytes() if gcode_path.is_file() else None
    return info, gcode_run, gcode


# --- Reading the outputs ---------------------------------------------------------------


def parse_info(text: str) -> dict:
    """The facts of one object's --info output; SlicerError for anything else.

    Strict: exactly one "[file]" line, first; then only "key = value" lines with known keys,
    each once, and every INFO_REQUIRED key. Returns {size_mm: [x, y, z], min_mm, max_mm,
    facets, manifold (bool), open_edges (None when absent), parts, volume_mm3, repairs:
    {key: count} for the repair lines present}.
    """
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    headers = [line for line in lines if line.startswith("[") and line.endswith("]")]
    if not headers or lines[0] != headers[0]:
        raise SlicerError("--info printed no object (no '[file]' line first)")
    if len(headers) > 1:
        raise SlicerError(f"--info printed {len(headers)} objects, not 1")
    known = {*INFO_REQUIRED, "open_edges", *INFO_REPAIRS}
    values: dict[str, str] = {}
    for line in lines[1:]:
        key, sep, value = line.partition("=")
        key, value = key.strip(), value.strip()
        if not sep or not key:
            raise SlicerError(f"--info line {line!r} is not 'key = value'")
        if key not in known:
            raise SlicerError(f"--info has an unknown key {key!r}")
        if key in values:
            raise SlicerError(f"--info gives {key!r} twice")
        values[key] = value
    missing = [k for k in INFO_REQUIRED if k not in values]
    if missing:
        raise SlicerError(f"--info lacks {', '.join(missing)}")
    if values["manifold"] not in ("yes", "no"):
        raise SlicerError(f"--info manifold is {values['manifold']!r}, not yes or no")
    numbers: dict[str, float | int] = {}
    for key, value in values.items():
        if key == "manifold":
            continue
        try:
            if key in INFO_COUNTS:
                if not re.fullmatch(r"\d+", value):
                    raise ValueError
                numbers[key] = int(value)
            else:
                numbers[key] = float(value)
                if not math.isfinite(numbers[key]):
                    raise ValueError
        except ValueError:
            raise SlicerError(f"--info {key} is {value!r}, not a "
                              f"{'count' if key in INFO_COUNTS else 'finite number'}") from None
    return {"size_mm": [numbers[k] for k in INFO_SIZES],
            "min_mm": [numbers[f"min_{a}"] for a in "xyz"],
            "max_mm": [numbers[f"max_{a}"] for a in "xyz"],
            "facets": numbers["number_of_facets"], "manifold": values["manifold"] == "yes",
            "open_edges": numbers.get("open_edges"), "parts": numbers["number_of_parts"],
            "volume_mm3": numbers["volume"],
            "repairs": {k: numbers[k] for k in INFO_REPAIRS if k in numbers}}


def _number(text: bytes, where: str) -> float:
    try:
        value = float(text)
    except ValueError:
        value = math.nan
    if not math.isfinite(value):
        raise SlicerError(f"the G-code has {where} {text.decode('ascii', 'replace')!r}, "
                          "not a number")
    return value


def gcode_layers(data: bytes) -> dict:
    """What PrusaSlicer's G-code prints, layer by layer. SlicerError for any form not read.

    Returns {layers: the number of ";LAYER_CHANGE" lines, z_mm: every ";Z:" value in
    order, extrusions: per layer, the number of extruding moves, filament_mm: per layer,
    the filament pushed by them, extrusion_z_mm: per layer, [lowest, highest] commanded Z
    of them (None for a layer with none), complete: whether the last non-empty line is
    PRUSA_GCODE_END}.

    Layer markers: PrusaSlicer writes ";LAYER_CHANGE" and then ";Z:<print_z>" for each
    layer (src/libslic3r/GCode.cpp, about line 2647), print_z through
    float_to_string_decimal_point, which on Windows is std::to_chars with
    chars_format::general and precision 6 (bundled_deps/localesutils/LocalesUtils.cpp,
    line 89): 6 significant digits, the precision z_tolerance assumes. Each ";Z:" must
    follow a ";LAYER_CHANGE", at most one per layer (a missing one is found by the count).

    Motion, read as written by the measured runs (the research record; Codex review
    2026-11-11, finding 1): G90 and M82 (absolute positions and extrusion), G92 E0 resets,
    G28, and G0/G1 with X, Y, Z, E and F words. An extruding move is a G0/G1 whose E is
    above the current E and whose X or Y changes the position; it must come after G90 and
    M82, with X, Y, Z and E all known, and after the first ";LAYER_CHANGE". It belongs to
    the layer of the last ";LAYER_CHANGE". X, Y and Z words have at most 3 decimals, as in
    every measured file, so a commanded Z is within half of 1e-3 of the value meant.
    Anything else that moves or extrudes is refused: G91, M83, arcs (G2/G3), firmware
    retraction (G10/G11), G92 on any axis but E, any other G-code, a word that is not one
    letter and a number, and a repeated word.

    Complete: every PrusaSlicer G-code written in the research and by tdmg slice (the
    owner models, the cube and the open cube; 14 files, 2026-11-11) ends with the
    configuration block, whose last line is PRUSA_GCODE_END, so a file cut short lacks it.
    """
    layers, zs, counts, filament, zrange = 0, [], [], [], []
    absolute_xy = absolute_e = False
    pos: dict[bytes, float | None] = dict.fromkeys((b"X", b"Y", b"Z", b"E"))
    last, z_this_layer = b"", False
    for raw in data.split(b"\n"):
        line = raw.rstrip(b"\r")
        if line.strip():
            last = line.strip()
        if line == b";LAYER_CHANGE":
            layers += 1
            counts.append(0)
            filament.append(0.0)
            zrange.append(None)
            z_this_layer = False
            continue
        if line.startswith(b";Z:"):
            if layers == 0 or z_this_layer:
                raise SlicerError("the G-code has a ;Z: line that does not follow its own "
                                  ";LAYER_CHANGE")
            z_this_layer = True
            zs.append(_number(line[3:], "a ;Z: line"))
            continue
        code = line.split(b";", 1)[0].split()
        if not code:
            continue
        cmd, words = code[0], code[1:]
        if cmd.startswith(b"M"):
            if cmd == b"M82":
                absolute_e = True
            elif cmd == b"M83":
                raise SlicerError("the G-code uses relative extrusion (M83), which this "
                                  "check does not read")
            continue
        if cmd == b"G90":
            absolute_xy = True
        elif cmd == b"G21":
            pass
        elif cmd == b"G28":
            pos.update({b"X": None, b"Y": None, b"Z": None})
        elif cmd in (b"G0", b"G1", b"G92"):
            new: dict[bytes, float] = {}
            for word in words:
                axis, text = word[:1], word[1:]
                if axis not in (b"X", b"Y", b"Z", b"E", b"F") or axis in new or not text:
                    shown = word.decode("ascii", "replace")
                    raise SlicerError(f"the G-code has a move word {shown!r} "
                                      "this check does not read")
                if axis in (b"X", b"Y", b"Z") and b"." in text and len(text.split(b".")[1]) > 3:
                    raise SlicerError(f"the G-code has {word.decode('ascii', 'replace')!r}, with "
                                      "more than the 3 decimals PrusaSlicer was measured to write")
                new[axis] = _number(text, f"a {axis.decode()} word")
            if cmd == b"G92":
                if set(new) - {b"E"}:
                    raise SlicerError("the G-code sets a position other than E with G92")
                pos.update(new)
                continue
            moves_xy = any(a in new and new[a] != pos[a] for a in (b"X", b"Y"))
            extrudes = b"E" in new and (pos[b"E"] is None or new[b"E"] > pos[b"E"])
            if extrudes and moves_xy:
                known = all(pos[a] is not None or a in new for a in (b"X", b"Y", b"Z", b"E"))
                if not (absolute_xy and absolute_e and known and pos[b"E"] is not None):
                    raise SlicerError("the G-code extrudes before G90, M82 and the position "
                                      "are all set")
                if layers == 0:
                    raise SlicerError("the G-code extrudes before its first ;LAYER_CHANGE")
                z = new.get(b"Z", pos[b"Z"])
                counts[-1] += 1
                filament[-1] += new[b"E"] - pos[b"E"]
                lo_hi = zrange[-1]
                zrange[-1] = [z, z] if lo_hi is None else [min(lo_hi[0], z), max(lo_hi[1], z)]
            pos.update({a: v for a, v in new.items() if a != b"F"})
        else:
            raise SlicerError(f"the G-code has {cmd.decode('ascii', 'replace')}, which this "
                              "check does not read")
    return {"layers": layers, "z_mm": zs, "extrusions": counts, "filament_mm": filament,
            "extrusion_z_mm": zrange, "complete": last == PRUSA_GCODE_END}


def prusa_gcode_hashes(data: bytes) -> dict:
    """The raw SHA-256, and one with line 1 blanked when it is the "generated by" line.

    That line holds the run's date and time; it was the only difference between two runs
    (research record, finding 4). Only line 1 is looked at, and its line end is kept, so
    any other change shows.
    """
    first, sep, rest = data.partition(b"\n")
    blanked = 1 if GENERATED_LINE.match(first) else 0
    normalised = ((b"\r" if first.endswith(b"\r") else b"") + sep + rest) if blanked else data
    return {"sha256": hashlib.sha256(data).hexdigest(),
            "normalised_sha256": hashlib.sha256(normalised).hexdigest(),
            "normalised_lines": blanked}


# --- Tolerances ------------------------------------------------------------------------


def _triangles(stl: bytes) -> np.ndarray:
    """(N, 3, 3) float64 vertices of each facet, in file order, as stored (float32)."""
    try:
        mesh = trimesh.load(io.BytesIO(stl), file_type="stl", process=False)
        tri = np.asarray(mesh.vertices, dtype=np.float64)[np.asarray(mesh.faces)]
    except (ValueError, TypeError, IndexError, AttributeError) as err:
        raise SlicerError(f"model.stl cannot be read as an STL: {err}") from None
    if tri.ndim != 3 or len(tri) == 0 or not np.isfinite(tri).all():
        raise SlicerError("model.stl has no facets, or a non-finite coordinate")
    return tri


def coordinate_max(stl: bytes) -> float:
    """The largest |coordinate| of the STL as stored."""
    return float(np.abs(_triangles(stl)).max())


def size_tolerance_mm(coordinate_max_mm: float) -> float:
    """How far a --info size may be from flat.json's extents_mm for the same STL.

    flat.json's extents are max - min of the stored float32 vertices (flat reads its STL
    back), so storage adds nothing. PrusaSlicer moves the vertices twice before it
    measures: ModelVolume::center_geometry_after_creation shifts them in float32 by minus
    the bounding-box centre, and ModelObject::raw_mesh shifts them back in double and
    stores float32 again (src/libslic3r/Model.cpp). Each rounding moves a coordinate by at
    most |value| x 2^-24, and both values are at most M, the largest |coordinate| (a
    centred one is at most half the extent). So each end of a size moves by at most
    2 M 2^-24 and the size by 4 M 2^-24 = 2 STL_COORD_RTOL M. As elsewhere, this is
    doubled to cover the shifts' own rounding and the double arithmetic:
    4 STL_COORD_RTOL M. Plus INFO_HALF_UNIT for the 6-decimal print. A numerical bound,
    not a rule. Emulating those steps in numpy gave the Roadie's and Oddie's printed sizes
    to all 6 decimals (2026-11-11), and the Roadie's differ from flat.json by 1.2e-6 mm,
    under this bound (2.9e-5 mm at M = 60 mm).
    """
    return INFO_HALF_UNIT + 4 * STL_COORD_RTOL * float(coordinate_max_mm)


def _gamma(n: int) -> float:
    """Higham's gamma_n = n u / (1 - n u) for float32: the bound on n roundings."""
    return n * U32 / (1 - n * U32)


def volume_error_bound(stl: bytes) -> float:
    """A bound on |PrusaSlicer's --info volume - the exact volume of the stored STL|.

    What PrusaSlicer computes (read in its 2.9.7 source): load_stl reads the binary STL's
    float32 vertices in file order (TriangleMesh::ReadSTLFile), repairs on import, and
    print_info prints the volume admesh computed then: get_volume in
    bundled_deps/admesh/admesh/util.cpp. For each facet with vertices a, b, c, with p the
    first vertex of the first facet, it adds, in float32,
        volume += (area * height) / 3.0f,  height = n . (a - p),  area = 0.5f * n . s,
    where n is the facet normal recomputed in float32 from the vertices (stl_calculate_normal,
    a cross product of the float32 edges b - a and c - a, scaled by float(1 / length)), and
    s is a cross-product sum computed in double from the vertices and stored as float32.
    The exact term is t = A h / 3 with A = |C| / 2, C = (b - a) x (c - a), h = n_C . (a - p).

    The bound, by standard float error analysis (Higham, Accuracy and Stability of Numerical
    Algorithms, 2nd ed., sections 2.2 and 3.1; u = 2^-24, gamma_k = k u / (1 - k u)), first
    for each facet, with L = |b - a| |c - a|, w = |a - p|, M the largest |coordinate|:
    - the computed C differs from C by eta <= (sqrt(3) gamma_2 (1 + u)^2 + 2u + u^2) L
      (each component is two products and a difference; the edges are rounded once);
    - so the normal's direction is off by delta <= 2 eta / |C| + gamma_2 (the scaling);
      delta is large for a sliver facet, which is why the bound uses the facets themselves;
    - height: |dh| <= w (delta (1 + u) + u + gamma_3 (1 + gamma_2)(1 + u)) (a - p rounded,
      a 3-term dot product);
    - area: |dA| <= A (delta + (1 + gamma_2)(u + gamma_3 (1 + u))) + 16 u64 M^2 (s rounded
      to float32, the dot product, and the double sum's rounding, u64 = 2^-53). The
      products in s are exact: a float32 times a float32 has at most 48 significant bits,
      which a double holds. Only the differences and sums round: each component of s is
      three differences of two products (each at most M^2, so each difference at most
      2 M^2) added twice, so it is off by at most 3 u64 2 M^2 + 2 u64 3 (2 M^2) = 18 u64 M^2,
      the vector by sqrt(3) x 18 u64 M^2 = 31.2 u64 M^2, and the area (half of n . s) by
      half of that, rounded up to 16 u64 M^2. It is negligible next to the float32 terms;
    - term: |dt| <= (|dA| (|h| + |dh|) + A |dh|) / 3 + gamma_2 (A + |dA|)(|h| + |dh|) / 3.
    Then the sum: each addition rounds its result S_k by at most u |S_k|, and |S_k| is at
    most |exact partial sum| + the term bounds so far + the error so far, which gives
    E_N = u sum_k (1 + u)^(N - k) r_k, r_k = |sum_{j<=k} t_j| + sum_{j<=k} |dt_j|.
    The bound is sum_k |dt_k| + E_N, evaluated here in double.

    Zeroed normals (Codex review 2026-11-11, finding 2): admesh sets a normal shorter than
    ADMESH_NORMAL_CUTOFF to zero, so that facet's computed term is exactly 0, not a
    rounding of t. The computed cross product is within eta of C, so a facet with
    |C| - eta < ADMESH_NORMAL_CUTOFF may be zeroed; its error is then |t| or the bound
    above, and the bound uses their sum. The height uses the facet's stored normal, which
    the import repair (stl_fix_normal_values, run before stl_calculate_volume in
    trianglemesh_repair_on_import, src/libslic3r/TriangleMesh.cpp) sets to this same
    recomputed one.

    It assumes the facets keep their file order and vertex order, which holds unless the
    import repair changed the mesh; portability_check FAILs before the volume when --info
    reports any repair. Second-order terms are left out; volume_tolerance_mm3 doubles the
    bound to cover them and the double arithmetic, as elsewhere. Checked 2026-11-11:
    emulating get_volume in numpy float32 gave PrusaSlicer's printed volumes exactly for
    the 20 mm cube (8000.000488), the Roadie (2277.742188) and the Oddie (5033.670898).
    The bound is a worst case: 2.8 mm3 (1.2e-3 relative) for the Roadie and 8.8 mm3
    (1.8e-3) for the Oddie, where the measured errors are 6e-7 and 4.4e-6 relative. Of it,
    the summation term E_N and the per-facet terms are of the same size for these models
    (Roadie 1.4 and 1.4 mm3, Oddie 3.7 and 5.2 mm3, 2026-11-11): the sum dominates for a
    model whose partial sums are large next to its facets' own errors, and sliver facets
    (large delta) make the per-facet terms grow. A random check of the bound against a
    float32 emulation of get_volume is in tests/test_portability.py.
    """
    tri = _triangles(stl)
    a, b, c = tri[:, 0], tri[:, 1], tri[:, 2]
    p = tri[0, 0]
    u, g2, g3 = U32, _gamma(2), _gamma(3)
    big = float(np.abs(tri).max())
    cross = np.cross(b - a, c - a)
    norm = np.linalg.norm(cross, axis=1)
    edges = np.linalg.norm(b - a, axis=1) * np.linalg.norm(c - a, axis=1)
    eta = (math.sqrt(3) * g2 * (1 + u) ** 2 + 2 * u + u * u) * edges
    # Two unit vectors are at most 2 apart, so delta never needs to exceed 2 + gamma_2; a
    # facet of zero area (exact term 0) gets that, and |h| <= w.
    flat = norm == 0
    safe = np.where(flat, 1.0, norm)
    delta = np.where(flat, 2 + g2, np.minimum(2 * eta / safe + g2, 2 + g2))
    area = norm / 2
    w = np.linalg.norm(a - p, axis=1)
    signed = np.einsum("ij,ij->i", cross / safe[:, None], a - p)
    height = np.where(flat, w, np.abs(signed))
    dh = w * (delta * (1 + u) + u + g3 * (1 + g2) * (1 + u))
    da = area * (delta + (1 + g2) * (u + g3 * (1 + u))) + 16 * U64 * big * big
    term_error = ((da * (height + dh) + area * dh) / 3
                  + g2 * (area + da) * (height + dh) / 3)
    exact = area * signed / 3
    term_error = term_error + np.where(norm - eta < ADMESH_NORMAL_CUTOFF, np.abs(exact), 0.0)
    r = np.abs(np.cumsum(exact)) + np.cumsum(term_error)
    n = len(r)
    growth = (1 + u) ** np.arange(n - 1, -1, -1, dtype=np.float64)
    return float(term_error.sum() + u * np.sum(r * growth))


def volume_tolerance_mm3(stl: bytes) -> float:
    """2 x volume_error_bound plus INFO_HALF_UNIT for the 6-decimal print."""
    return 2 * volume_error_bound(stl) + INFO_HALF_UNIT


# --- The check -------------------------------------------------------------------------


@dataclass(frozen=True)
class Expected:
    """What PrusaSlicer must report: flat.json's mesh facts and the allowed layers."""
    parts: int
    facets: int
    size_mm: list[float]
    volume_mm3: float
    layer_counts: list[int]
    first_layer_mm: float
    layer_mm: float
    size_tol_mm: float
    volume_tol_mm3: float | None     # None: the volume is not judged (portability_check)

    def as_dict(self) -> dict:
        return {"parts": self.parts, "facets": self.facets, "size_mm": self.size_mm,
                "volume_mm3": self.volume_mm3, "layer_counts": self.layer_counts}


def not_configured_check() -> CheckResult:
    return CheckResult("F6.portability", "UNKNOWN", None, None, None, NOT_CONFIGURED)


def _ran(name: str, run: PrusaRun, timeout_rule: str | None) -> tuple[str | None, str | None]:
    """(reason, rule) when a run was stopped or exited nonzero, else (None, None)."""
    if run.timed_out:
        return f"{name} was stopped after the {run.timeout_s:g} s timeout", timeout_rule
    if run.returncode != 0:
        last = run.stderr.strip().splitlines()[-1] if run.stderr.strip() else ""
        return f"{name} exited {run.returncode}" + (f": {last}" if last else ""), None
    return None, None


def _info_failure(info: dict, exp: Expected, model: str = "model.stl",
                  source: str = "flat.json") -> str | None:
    if not info["manifold"] or info["open_edges"] is not None:     # any line, even 0
        return f"PrusaSlicer reads {model} as not manifold (open_edges {info['open_edges']})"
    if info["repairs"]:
        found = ", ".join(f"{k} {v}" for k, v in info["repairs"].items())
        return f"PrusaSlicer repaired the mesh on import ({found})"
    if info["parts"] != exp.parts:
        bodies = "body" if exp.parts == 1 else "bodies"
        return f"number_of_parts {info['parts']}, not the {exp.parts} {bodies} of {source}"
    if info["facets"] != exp.facets:
        return f"number_of_facets {info['facets']}, not the {exp.facets} triangles of {source}"
    for key, got, want in zip(INFO_SIZES, info["size_mm"], exp.size_mm, strict=True):
        if abs(got - want) > exp.size_tol_mm:
            return (f"{key} {got:g} mm, not {want:g} mm ({source}; tolerance "
                    f"{exp.size_tol_mm:.2g} mm)")
    if (exp.volume_tol_mm3 is not None
            and abs(info["volume_mm3"] - exp.volume_mm3) > exp.volume_tol_mm3):
        return (f"volume {info['volume_mm3']:g} mm3, not {exp.volume_mm3:g} mm3 ({source}; "
                f"tolerance {exp.volume_tol_mm3:.2g} mm3)")
    return None


# A commanded Z word is within PRUSA_XYZ_HALF_UNIT of the layer's print_z; doubled for the
# float arithmetic, as elsewhere. A numerical bound, far below a layer height.
COMMANDED_Z_TOL_MM = 2 * PRUSA_XYZ_HALF_UNIT


def _motion_failure(layers: dict, exp: Expected) -> str | None:
    """The first layer with no extrusion, or with an extrusion away from its height."""
    n = layers["layers"]
    for i, (count, zr) in enumerate(zip(layers["extrusions"], layers["extrusion_z_mm"],
                                        strict=True)):
        if count == 0:
            return f"layer {i + 1} of {n} has no extruding move"
        want = exp.first_layer_mm + i * exp.layer_mm
        for z in zr:
            if abs(z - want) > COMMANDED_Z_TOL_MM:
                return (f"layer {i + 1} of {n} extrudes at Z {z:g} mm, not at its "
                        f"{want:g} mm")
    return None


def portability_check(info_run: PrusaRun, gcode_run: PrusaRun, gcode: bytes | None,
                      exp: Expected, timeout_rule: str | None, *, model: str = "model.stl",
                      source: str = "flat.json", meaning: str | None = None,
                      volume_unjudged: str | None = None) -> tuple[CheckResult, dict]:
    """F6.portability from both runs, and the measurements for the record.

    PASS only if --info exits 0 and reads a manifold, unrepaired mesh with flat.json's
    parts, facets, sizes and volume (within size_tolerance_mm and volume_tolerance_mm3),
    and --export-gcode exits 0 and writes a non-empty G-code whose ";LAYER_CHANGE" count is
    allowed, with one ";Z:" per layer, and whose i-th ";Z:" (from 0) is
    first_layer + i x layer (PrusaSlicer stacks whole layers: generate_object_layers in
    src/libslic3r/Slicing.cpp), each within z_tolerance, the Z tolerance F3 uses. So the
    last one is the expected top. The G-code must also be complete, and every layer must
    have at least one extruding move, each at that layer's height within
    COMMANDED_Z_TOL_MM (gcode_layers). That shows plastic is laid at every layer to the
    top; it does not show that each layer is fully printed, which F3 judges for the
    OrcaSlicer G-code only. An open_edges line, even "open_edges = 0", is a FAIL,
    as the plan says. Otherwise FAIL, naming the first
    condition that failed. Output that cannot be read is a FAIL, not UNKNOWN: a configured,
    verified second reader that does not confirm the file has not passed it.

    model and source name the file and the record in the notes; meaning replaces
    PORTABILITY_MEANING and SHARED_READER_NOTE in a PASS note. With exp.volume_tol_mm3
    None the volume is not compared, and a run that passes every other condition is
    UNKNOWN, not PASS, with volume_unjudged as the reason (tdmg.color_slicing: no
    tolerance is known for PrusaSlicer's 3MF volume).
    """
    parsed, info_problem = None, None
    if info_run.returncode == 0 and not info_run.timed_out:
        try:
            parsed = parse_info(info_run.stdout)
        except SlicerError as err:
            info_problem = f"cannot read --info: {err}"
    layers = {"layers": None, "z_mm": [], "extrusions": [], "filament_mm": [],
              "extrusion_z_mm": [], "complete": False}
    gcode_problem = None
    if gcode:
        try:
            layers = gcode_layers(gcode)
        except SlicerError as err:
            gcode_problem = f"cannot read the G-code: {err}"
    n, zs = layers["layers"], layers["z_mm"]
    last_z = zs[-1] if zs else None
    top = exp.first_layer_mm + (n - 1) * exp.layer_mm if n else None
    z_tol = z_tolerance(top, last_z, 0.0) if top is not None and last_z is not None else None

    reason, rule = _ran("--info", info_run, timeout_rule)
    if reason is None:
        reason = info_problem or _info_failure(parsed, exp, model, source)
    if reason is None:
        reason, rule = _ran("--export-gcode", gcode_run, timeout_rule)
    if reason is None and gcode is None:
        said = (gcode_run.stdout.strip() or gcode_run.stderr.strip()).splitlines()
        reason = ("--export-gcode exited 0 but wrote no G-code"
                  + (f": {said[-1]}" if said else ""))
    if reason is None and not gcode:
        reason = "--export-gcode wrote an empty G-code"
    if reason is None:
        reason = gcode_problem
    if reason is None and not layers["complete"]:
        reason = (f"the G-code does not end with {PRUSA_GCODE_END.decode()!r}: it is "
                  "incomplete")
    if reason is None and n not in exp.layer_counts:
        reason = (f"the G-code has {n} layers, not one of {exp.layer_counts}: it is "
                  "truncated, as an open mesh slices")
    if reason is None and len(zs) != n:
        reason = f"the G-code has {len(zs)} ;Z: lines for {n} layers"
    if reason is None:
        for i, z in enumerate(zs):
            want = exp.first_layer_mm + i * exp.layer_mm
            if abs(z - want) > z_tolerance(want, z, 0.0):
                reason = f"its ;Z: at layer {i + 1} of {n} is {z:g} mm, not {want:g} mm"
                break
    if reason is None:
        reason = _motion_failure(layers, exp)

    measured = {"parts": parsed and parsed["parts"], "facets": parsed and parsed["facets"],
                "size_mm": parsed and parsed["size_mm"],
                "volume_mm3": parsed and parsed["volume_mm3"], "layers": n,
                "last_z_mm": last_z,
                "min_extrusions_per_layer": min(layers["extrusions"], default=None)}
    threshold = {"parts": exp.parts, "facets": exp.facets, "size_mm": exp.size_mm,
                 "size_tol_mm": exp.size_tol_mm, "volume_mm3": exp.volume_mm3,
                 "volume_tol_mm3": exp.volume_tol_mm3, "layers": exp.layer_counts,
                 "top_z_mm": top}
    if reason is None and exp.volume_tol_mm3 is None:
        check = CheckResult("F6.portability", "UNKNOWN", measured, threshold, None,
                            "PrusaSlicer 2.9.7: every condition passed except the volume, "
                            f"which is not judged: {volume_unjudged}. {PRUSA_GCODE_NOTE}")
    elif reason is None:
        said = meaning or f"{PORTABILITY_MEANING}. {SHARED_READER_NOTE}"
        check = CheckResult("F6.portability", "PASS", measured, threshold, None,
                            f"{said}. {PRUSA_GCODE_NOTE}")
    else:
        check = CheckResult("F6.portability", "FAIL", measured, threshold, rule,
                            f"PrusaSlicer 2.9.7: {reason}")
    measurements = {
        "info": {**info_run.summary(), "parsed": parsed},
        "gcode": {**gcode_run.summary(), "bytes": None if gcode is None else len(gcode),
                  "layers": n, "last_z_mm": last_z, "expected_top_mm": top,
                  "complete": layers["complete"], "extrusions": layers["extrusions"],
                  "filament_mm": [round(f, 5) for f in layers["filament_mm"]],
                  "extrusion_z_mm": layers["extrusion_z_mm"]},
        "tolerances": {"size_mm": exp.size_tol_mm, "volume_mm3": exp.volume_tol_mm3,
                       "z_mm": z_tol, "commanded_z_mm": COMMANDED_Z_TOL_MM}}
    return check, measurements
