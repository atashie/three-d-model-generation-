"""Generate documentation tables from the registries in code.

    uv run python scripts/gen_docs.py          # write the generated files
    uv run python scripts/gen_docs.py --check  # exit 1 if any generated file is stale (CI)

Generated files carry a header saying so. Edit the registries, not the output.
"""

from __future__ import annotations

import sys
from pathlib import Path

from tdmg.paths import DOCS_DIR, REPO_ROOT
from tdmg.recipes import ATTRIBUTE_LABELS, RECIPES
from tdmg.rules import Rule, rule_files

HEADER = "<!-- GENERATED by scripts/gen_docs.py from {src}. Do not edit by hand. -->\n\n"


def _fmt(v: object) -> str:
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return f"{v:g}"
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _qualifiers(r: Rule) -> str:
    parts = [f"{k} = {_fmt(v)}" for k, v in r.conditions.items()]
    if r.measured_as:
        parts.append(f"measured as {r.measured_as}")
    if r.scales_with_model is False:
        parts.append("absolute: does not scale with the model")
    if r.notes:
        parts.append(r.notes)
    return _cell("; ".join(parts))


def _rule_row(r: Rule) -> str:
    rng = f"{_fmt(r.range[0])}–{_fmt(r.range[1])}" if r.range else ""
    applies = "all" if r.applies_to == "all" else ", ".join(
        v for vals in r.applies_to.values() for v in vals)
    return (f"| `{r.id}` | {_cell(r.summary)} | {_fmt(r.default)} | {rng} | {r.unit} | {r.kind} | "
            f"{r.best_provenance} / {r.best_validation} | {applies} | {_qualifiers(r)} |")


def render_rules() -> str:
    out = [HEADER.format(src="rules/*.yaml"), "# Design rules\n\n",
           ("Every number the pipeline uses. *Provenance / validation* shows the strongest "
            "evidence for "),
           ("each rule (see docs/PLAN.md section 7). Sources and exact quotes are in the YAML "
            "files.\n")]
    for stem, rules in rule_files().items():
        out.append(f"\n## `rules/{stem}.yaml`\n\n")
        out.append("| Rule | Summary | Default | Range | Unit | Kind | Provenance / validation "
                   "| Applies to | Conditions and notes |\n")
        out.append("|---|---|---|---|---|---|---|---|---|\n")
        out.extend(_rule_row(r) + "\n" for r in rules)
    return "".join(out)


def render_recipes() -> str:
    out = [HEADER.format(src="src/tdmg/recipes.py"), "# Recipe status\n\n",
           "A recipe is a named combination of the four attributes that the project implements. ",
           "See [README.md](README.md) for the attribute model.\n\n",
           "| Recipe | Name | Geometry | Joints | Color | Assembly | Example | Phase | Status |\n",
           "|---|---|---|---|---|---|---|---|---|\n"]
    for r in RECIPES:
        colors = ", ".join(f"{c.value} {ATTRIBUTE_LABELS[c.value]}" for c in r.colors)
        out.append(
            f"| {r.id} | {r.name} | {r.geometry.value} {ATTRIBUTE_LABELS[r.geometry.value]} | "
            f"{r.articulation.value} {ATTRIBUTE_LABELS[r.articulation.value]} | {colors} | "
            f"{r.assembly.value} {ATTRIBUTE_LABELS[r.assembly.value]} | {r.example} | "
            f"{r.roadmap_phase} | {r.status.value} |\n")
    return "".join(out)


TARGETS: dict[Path, callable] = {
    DOCS_DIR / "reference" / "rules.md": render_rules,
    DOCS_DIR / "print-types" / "recipes.md": render_recipes,
}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, render in TARGETS.items():
        text = render()
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(REPO_ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO_ROOT)}")
    if stale:
        print("stale generated docs (run: uv run python scripts/gen_docs.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
