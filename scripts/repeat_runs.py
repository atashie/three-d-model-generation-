# The only G-code line allowed to differ, by slicer: (1-based line number, pattern).
# Measured in research/verification/2026-11-16-repeatability/ (every differing G-code
# file differed in exactly this line); the versions are the pinned slicers.
ORCA_TIMESTAMP = (2, re.compile(
    r"; generated by OrcaSlicer 2\.5\.0 on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}"))
PRUSA_TIMESTAMP = (1, re.compile(
    r"; generated by PrusaSlicer 2\.9\.7 on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2} UTC"))

TEXT_SUFFIXES = {".gcode", ".txt", ".md", ".log", ".failed", ".yaml", ".csv"}
ZIP_SUFFIXES = {".3mf"}
EXAMPLE_LINES = 3      # differing text lines shown per file in the report
# tdmg colors settings sources (tdmg.color_config.Source); any other value stops the plan.
COLOR_SOURCES = {"flag", "config", "profile", "rule", "default"}
COLOR_FLAGS = {"colors": "--colors", "extract": "--extract", "edges": "--edges",
               "base": "--base", "outlines": "--outlines"}
_PLAIN_KEY = re.compile(r"[^.\[\]/\"]+")


class PlanError(RuntimeError):
    """A job cannot be rebuilt from its records alone."""


def cmdline(args: list[str]) -> str:
    """A command line that can be pasted into this OS's shell."""
    return subprocess.list2cmdline(args) if os.name == "nt" else shlex.join(args)


def format_value(value) -> str:
    """A recorded value as a CLI argument that parses back to the same value."""
    return repr(value) if isinstance(value, float) else str(value)


# ---------------------------------------------------------------- comparison helpers

def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def json_diff_keys(a, b, path: tuple = ()) -> list[tuple]:
    """The paths (tuples of dict keys and list indices) at which a and b differ.

    Dicts are compared key by key (a key in one only is reported at its path). Lists are
    compared index by index; extra items in the longer list are reported at their index.
    A type change, or unequal scalars, is reported at that path. 1 and 1.0 are equal, as in
    JSON; True and 1 are not. Keys come in sorted order.
    """
    if isinstance(a, dict) and isinstance(b, dict):
        out: list[tuple] = []
        for key in sorted(set(a) | set(b)):
            sub = (*path, key)
            if key not in a or key not in b:
                out.append(sub)
            else:
                out += json_diff_keys(a[key], b[key], sub)
        return out
    if isinstance(a, list) and isinstance(b, list):
        out = []
        for i in range(max(len(a), len(b))):
            sub = (*path, i)
            if i >= len(a) or i >= len(b):
                out.append(sub)
            else:
                out += json_diff_keys(a[i], b[i], sub)
        return out
    if isinstance(a, bool) != isinstance(b, bool) or type(a) is not type(b) and not (
            isinstance(a, (int, float)) and isinstance(b, (int, float))):
        return [path]
    return [] if a == b else [path]


def render_path(keys: tuple) -> str:
    """$ then .key, ["key"] (JSON-quoted, for a key with . / [ ] or " in it) or [index].
    A "*" index (from generalize) renders as [*]."""
    out = "$"
    for k in keys:
        if isinstance(k, int) or k == ("*",):
            out += f"[{'*' if k == ('*',) else k}]"
        elif _PLAIN_KEY.fullmatch(k):
            out += f".{k}"
        else:
            out += f"[{json.dumps(k, ensure_ascii=False)}]"
    return out


def json_diff_paths(a, b) -> list[str]:
    return [render_path(k) for k in json_diff_keys(a, b)]


def generalize(path: str) -> str:
    """A rendered JSON path with every list index replaced by [*]."""
    return re.sub(r"\[\d+\]", "[*]", path)


def generalize_keys(keys: tuple) -> tuple:
    return tuple(("*",) if isinstance(k, int) else k for k in keys)


def _text_diff(a: bytes, b: bytes) -> dict:
    """Lines compared by position; lines past the end of the shorter file count as
    differing (no alignment: an inserted line makes the rest differ)."""
    la, lb = a.decode("utf-8", "replace").splitlines(), b.decode("utf-8", "replace").splitlines()
    differing = [(i, x, y) for i, (x, y) in enumerate(zip(la, lb)) if x != y]
    return {"lines_a": len(la), "lines_b": len(lb), "line_counts_differ": len(la) != len(lb),
            "differing_lines": len(differing) + abs(len(la) - len(lb)),
            "examples": [{"line": i + 1, "a": x[:200], "b": y[:200]}
                         for i, x, y in differing[:EXAMPLE_LINES]]}


def _is_gcode(path: Path) -> bool:
    name = path.name.removesuffix(".failed")
    return name.endswith((".gcode", ".gcode.txt"))


def _gcode_check(path: Path, a: bytes, b: bytes) -> dict:
    """timestamp_only: the files differ in exactly one line, the slicer's timestamp line
    (ORCA_TIMESTAMP or PRUSA_TIMESTAMP, by file name), and it matches the pattern in both.
    normalised_equal: tdmg's own normalised hashes (as written in slice.json) are equal."""
    prusa = "prusaslicer" in path.name
    line_no, pattern = PRUSA_TIMESTAMP if prusa else ORCA_TIMESTAMP
    la, lb = a.split(b"\n"), b.split(b"\n")
    diff = [i for i, (x, y) in enumerate(zip(la, lb)) if x != y]
    ok = (len(la) == len(lb) and diff == [line_no - 1]
          and all(pattern.fullmatch(f[line_no - 1].rstrip(b"\r").decode("utf-8", "replace"))
                  for f in (la, lb)))
    hashes = prusa_gcode_hashes if prusa else gcode_hashes
    return {"timestamp_only": ok,
            "normalised_equal": hashes(a)["normalised_sha256"] == hashes(b)["normalised_sha256"]}


def _zip_diff(pa: Path, pb: Path) -> dict:
    with zipfile.ZipFile(pa) as za, zipfile.ZipFile(pb) as zb:
        ma = {i.filename: i for i in za.infolist()}
        mb = {i.filename: i for i in zb.infolist()}
        differ = sorted(n for n in set(ma) & set(mb) if za.read(n) != zb.read(n))
        meta = sorted(n for n in set(ma) & set(mb)
                      if (ma[n].date_time, ma[n].compress_type) !=
                      (mb[n].date_time, mb[n].compress_type))
        return {"only_a": sorted(set(ma) - set(mb)), "only_b": sorted(set(mb) - set(ma)),
                "members_differ": differ, "member_metadata_differ": meta}


def compare_file(pa: Path, pb: Path) -> dict:
    a, b = pa.read_bytes(), pb.read_bytes()
    entry = {"identical": a == b, "sha256_a": hashlib.sha256(a).hexdigest(),
             "sha256_b": hashlib.sha256(b).hexdigest()}
    if a == b:
        return entry
    if pa.suffix == ".json":
        try:
            keys = json_diff_keys(json.loads(a), json.loads(b))
        except ValueError as e:
            entry["json_error"] = str(e)
        else:
            entry["json_paths"] = [render_path(k) for k in keys]
            entry["json_keys"] = [list(k) for k in keys]
            if not keys:
                entry["note"] = "same JSON value, different bytes"
    elif pa.suffix in ZIP_SUFFIXES:
        entry["zip"] = _zip_diff(pa, pb)
    elif pa.suffix in TEXT_SUFFIXES:
        entry["text"] = _text_diff(a, b)
    if _is_gcode(pa):
        entry["gcode"] = _gcode_check(pa, a, b)
    return entry


def _files(root: Path) -> set[str]:
    return {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()}


def compare_runs(run_a: Path, run_b: Path) -> dict[str, dict]:
    """Every file under either run (logs aside), by relative path."""
    fa = {f for f in _files(run_a) if not f.startswith("_logs/")}
    fb = {f for f in _files(run_b) if not f.startswith("_logs/")}
    out = {}
    for rel in sorted(fa | fb):
        if rel not in fa or rel not in fb:
            out[rel] = {"identical": False, "only_in": "run-a" if rel in fa else "run-b"}
        else:
            out[rel] = compare_file(run_a / rel, run_b / rel)
    return out


# ---------------------------------------------------------------- recorded inputs

def _load(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise PlanError(f"{path}: cannot read the record: {e}") from None


@contextlib.contextmanager
def _reading(path):
    """Turn a missing or malformed field of the record at path into a PlanError."""
    try:
        yield
    except (KeyError, TypeError, IndexError, AttributeError, ValueError) as e:
        if isinstance(e, PlanError):
            raise
        raise PlanError(f"{path}: missing or malformed field ({type(e).__name__}: {e})"
                        ) from None


def _by_sha(folder: Path, name: str, sha: str) -> Path:
    """A record `name` under folder/*/ whose file SHA-256 is sha. Several folders can hold
    byte-identical copies; the first by path is returned (equal bytes, equal inputs)."""
    hits = sorted(p for p in folder.glob(f"*/{name}") if sha256_file(p) == sha)
    if not hits:
        raise PlanError(f"no {folder}/*/{name} has SHA-256 {sha}")
    return hits[0]


def _by_field(folder: Path, name: str, key: str, value: str) -> list[Path]:
    return sorted(p for p in folder.glob(f"*/{name}") if _load(p).get(key) == value)


@dataclass
class Step:
    name: str                  # also the output folder, relative to the run folder
    args: list[str]            # CLI arguments after `tdmg`; {run} is the run folder
    expect_exit: set[int] = field(default_factory=lambda: {0})


def _rule_or_flag(control: dict, flag: str) -> list[str]:
    """No flag when the value came from its rule (the run then uses today's rule value);
    else the flag with the recorded value."""
    if control.get("rule"):
        return []
    return [flag, format_value(control["value"])]


def select_step(name: str, sel_json: Path, images_dir: Path) -> Step:
    rec = _load(sel_json)
    with _reading(sel_json):
        controls = rec["controls"]
        if controls.get("source") != "controls":
            raise PlanError(f"{sel_json}: made from a mask ({controls.get('source')}); "
                            "the mask file is not recorded")
        image = images_dir / rec["input"]["name"]
        if not image.is_file():
            raise PlanError(f"{image}: source image not found")
        if sha256_file(image) != rec["input"]["file_sha256"]:
            raise PlanError(f"{image}: SHA-256 differs from {sel_json} input.file_sha256")
        args = ["select", str(image), "--out", "{run}/" + name]
        interp = rec["interpretation"]
        if interp.get("machine_interpreted"):
            raise PlanError(f"{sel_json}: machine-interpreted instructions")
        if interp.get("text") is not None:
            args += ["--instructions", interp["text"]]
        args += _rule_or_flag(controls["alpha_min"], "--alpha-min")
        if "color_tolerance" in controls:
            args += _rule_or_flag(controls["color_tolerance"], "--tolerance")
        for x, y in controls["remove_at"]:
            args += ["--remove-at", f"{x},{y}"]
        for x, y in controls["keep_at"]:
            args += ["--keep-at", f"{x},{y}"]
    return Step(name, args)


def color_flags(settings: dict, path) -> list[str]:
    """CLI flags for the settings that came from flags; an unknown source stops the plan."""
    out = []
    for key, source in sorted(settings["sources"].items()):
        if source not in COLOR_SOURCES:
            raise PlanError(f"{path}: {key} has unknown source {source!r}")
        if source == "flag":
            if key not in COLOR_FLAGS:
                raise PlanError(f"{path}: {key} from a flag that does not exist")
            out += [COLOR_FLAGS[key], format_value(settings["settings"][key])]
    return out


def _slice_flags(slice_rec: dict, path: Path) -> list[str]:
    """--timeout-s only if not from its rule; refuse a skipped tree check (not PRINTABLE)."""
    params = slice_rec["params"]
    flags = _rule_or_flag(params["timeout_s"], "--timeout-s")
    if "prusaslicer_timeout_s" in params and not params["prusaslicer_timeout_s"].get("rule"):
        raise PlanError(f"{path}: PrusaSlicer timeout not from its rule; --timeout-s sets both")
    if not slice_rec["slicer"]["app_tree_verified"]:
        raise PlanError(f"{path}: made with --skip-tree-check")
    return flags


def _uses_prusa(slice_rec: dict) -> bool:
    return bool(slice_rec["portability"].get("configured"))


def _colors_record(records: Path, colored_json: Path, colors_id: str, job: str) -> Path:
    hits = _by_field(records / "colors-runs", "colors.json", "colors_id", colors_id)
    named = [h for h in hits if h.parent.name == job]
    if named:
        return named[0]
    if len(hits) == 1:
        return hits[0]
    raise PlanError(f"{colored_json}: {len(hits)} colors.json files have colors_id "
                    f"{colors_id} and none is in a folder named {job}")


def plan_jobs(records: Path, configs: Path, images_dir: Path, slicer_dir: Path,
              prusaslicer_dir: Path) -> tuple[list[Step], list[dict]]:
    """The steps of one run, and how each job's inputs were traced (for the report)."""
    steps: list[Step] = []
    trace: list[dict] = []
    selected: dict[str, str] = {}     # selection.json sha -> step name

    def selection(sel_sha: str) -> str:
        if sel_sha not in selected:
            sel_json = _by_sha(records / "selection-runs", "selection.json", sel_sha)
            name = "select/" + sel_json.parent.name
            steps.append(select_step(name, sel_json, images_dir))
            selected[sel_sha] = name
            trace.append({"step": name, "from": sel_json.as_posix()})
        return selected[sel_sha]

    slicers = ["--slicer-dir", str(slicer_dir)]
    for job in R1_JOBS:
        sl_path = records / SLICE_RECORDS / job / "slice.json"
        sl = _load(sl_path)
        with _reading(sl_path):
            flat_json = _by_sha(records / "flat-runs", "flat.json",
                                sl["links"]["flat_record_sha256"])
            prusa = ["--prusaslicer-dir", str(prusaslicer_dir)] if _uses_prusa(sl) else []
            slice_flags = _slice_flags(sl, sl_path)
        fl = _load(flat_json)
        with _reading(flat_json):
            sel_id = fl["selection"]["selection_id"]
            sel_shas = {sha256_file(p) for p in (records / "selection-runs").glob(
                "*/selection.json") if _load(p).get("selection_id") == sel_id}
            if len(sel_shas) != 1:
                raise PlanError(f"{flat_json}: {len(sel_shas)} distinct selection.json files "
                                "have its selection_id")
            sel = selection(sel_shas.pop())
            p = fl["params"]
            smooth = _rule_or_flag(p["smoothing"]["sigma_px"], "--smooth-px")
            flat_name = f"flat/{job}"
            steps.append(Step(flat_name, [
                "flat", "{run}/" + sel, "--width-mm", format_value(p["width_mm"]),
                "--thickness-mm", format_value(p["thickness_mm"]), "--printer", p["printer"],
                *smooth, "--out", "{run}/" + flat_name]))
        steps.append(Step(f"slice/{job}", ["slice", "{run}/" + flat_name, *slicers, *prusa,
                                           *slice_flags, "--out", "{run}/slice/" + job],
                          expect_exit={sl_exit(records, job)}))
        trace.append({"step": flat_name, "from": flat_json.as_posix()})
        trace.append({"step": f"slice/{job}", "from": sl_path.as_posix()})

    config_by_sha = {sha256_file(c): c for c in sorted(configs.glob("*.yaml"))}
    for job in COLOR_JOBS:
        sl_path = records / SLICE_RECORDS / job / "slice.json"
        sl = _load(sl_path)
        with _reading(sl_path):
            colored_json = _by_sha(records / "colored-runs", "colored.json",
                                   sl["links"]["colored_record_sha256"])
            prusa = ["--prusaslicer-dir", str(prusaslicer_dir)] if _uses_prusa(sl) else []
            slice_args = ["--face", sl["params"]["face"], *_slice_flags(sl, sl_path)]
        cd = _load(colored_json)
        with _reading(colored_json):
            colors_json = _colors_record(records, colored_json, cd["identity"]["colors_id"],
                                         job)
            p = cd["identity"]["params"]
            if not p["smoothing"]["sigma_px"].get("rule"):
                raise PlanError(f"{colored_json}: smoothing not from its rule (not allowed "
                                "with --colors)")
            colored_params = ["--thickness-mm", format_value(p["thickness_mm"]),
                              "--width-mm", format_value(p["width_mm"]),
                              "--printer", p["printer"]]
        co = _load(colors_json)
        with _reading(colors_json):
            sel = selection(co["input"]["selection_json_sha256"])
            cargs = ["colors", "{run}/" + sel, "--width-mm", format_value(co["width_mm"])]
            st = co["settings"]
            cargs += color_flags(st, colors_json)
            config = None
            if st["config_sha256"] is not None:
                config = config_by_sha.get(st["config_sha256"])
                if config is None:
                    raise PlanError(f"{colors_json}: no config in {configs} has SHA-256 "
                                    f"{st['config_sha256']}")
                cargs += ["--config", str(config)]
            if co["printer"] != "bambu-a1":    # tdmg colors has no --printer: it is fixed
                raise PlanError(f"{colors_json}: printer {co['printer']}, not the CLI's")
        colors_name = f"colors/{job}"
        steps.append(Step(colors_name, [*cargs, "--out", "{run}/" + colors_name]))
        colored_name = f"colored/{job}"
        steps.append(Step(colored_name, ["flat", "{run}/" + sel, "--colors",
                                         "{run}/" + colors_name, *colored_params,
                                         "--out", "{run}/" + colored_name]))
        steps.append(Step(f"slice/{job}", ["slice", "{run}/" + colored_name, *slicers, *prusa,
                                           *slice_args, "--out", "{run}/slice/" + job],
                          expect_exit={sl_exit(records, job)}))
        trace += [{"step": colors_name, "from": colors_json.as_posix(),
                   "config": None if config is None else config.as_posix()},
                  {"step": colored_name, "from": colored_json.as_posix()},
                  {"step": f"slice/{job}", "from": sl_path.as_posix()}]

    strip_path = records / STRIP_RECORD
    with _reading(strip_path):
        sp = _load(strip_path)["params"]
        if not sp["check_tree"]:
            raise PlanError(f"{strip_path}: made without the tree check")
        timeout = _rule_or_flag(sp["timeout_s"], "--timeout-s")
    steps.append(Step("strip", ["strip", "{run}/strip", *slicers, *timeout]))
    trace.append({"step": "strip", "from": strip_path.as_posix()})
    return steps, trace


_EXIT_LINE = re.compile(r"exit (-?\d+)")


def _last_exit(text: str) -> int | None:
    """N from the last non-empty line when it is 'exit N', else None."""
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    m = _EXIT_LINE.fullmatch(lines[-1]) if lines else None
    return int(m.group(1)) if m else None


def sl_exit(records: Path, job: str) -> int:
    """The exit code of the recorded slice run: the last non-empty line of the recorded
    command output SLICE_RECORDS/<job>.txt, which must read 'exit N'."""
    txt = records / SLICE_RECORDS / f"{job}.txt"
    try:
        code = _last_exit(txt.read_text(encoding="utf-8", errors="replace"))
    except OSError as e:
        raise PlanError(f"{txt}: {e}") from None
    if code is None:
        raise PlanError(f"{txt}: the last line is not 'exit N'")
    return code


# ---------------------------------------------------------------- running

def _log_path(run_dir: Path, step: Step) -> Path:
    return run_dir / "_logs" / (step.name.replace("/", "__") + ".txt")


def run_steps(steps: list[Step], run_dir: Path, cwd: Path) -> list[dict]:
    if run_dir.exists():
        raise SystemExit(f"{run_dir} exists; give a fresh --out")
    (run_dir / "_logs").mkdir(parents=True)
    results = []
    for step in steps:
        args = [a.replace("{run}", run_dir.as_posix()) for a in step.args]
        t0 = time.monotonic()
        proc = subprocess.run([sys.executable, "-m", "tdmg.cli", *args], check=False,
                              cwd=cwd, capture_output=True, text=True, encoding="utf-8",
                              errors="replace")
        seconds = time.monotonic() - t0
        log = _log_path(run_dir, step)
        log.write_text(f"$ {cmdline(['tdmg', *args])}\n{proc.stdout}"
                       f"--- stderr\n{proc.stderr}exit {proc.returncode}\n", encoding="utf-8")
        ok = proc.returncode in step.expect_exit
        print(f"{run_dir.name} {step.name}: exit {proc.returncode}"
              f"{'' if ok else ' (UNEXPECTED, recorded ' + str(sorted(step.expect_exit)) + ')'}"
              f" in {seconds:.0f} s", flush=True)
        results.append({"step": step.name, "args": args, "exit": proc.returncode,
                        "expected_exit": sorted(step.expect_exit), "seconds": round(seconds, 1)})
        if proc.returncode == 2:
            raise SystemExit(f"{step.name} failed with exit 2; see {log}")
    return results


def runs_from_logs(steps: list[Step], run_dir: Path) -> list[dict]:
    """The step results of an earlier run, read back from its logs (no times: they are
    not in the logs). A missing log or exit line gives exit None."""
    out = []
    for step in steps:
        log = _log_path(run_dir, step)
        code = _last_exit(log.read_text(encoding="utf-8")) if log.is_file() else None
        out.append({"step": step.name,
                    "args": [a.replace("{run}", run_dir.as_posix()) for a in step.args],
                    "exit": code, "expected_exit": sorted(step.expect_exit),
                    "seconds": None})
    return out


def unexpected_exits(steps: list[Step], runs: dict[str, list[dict]]) -> list[dict]:
    """The steps whose exit in either run is not the recorded one."""
    by_run = {name: {r["step"]: r["exit"] for r in res} for name, res in runs.items()}
    out = []
    for step in steps:
        got = {name: by_run[name].get(step.name) for name in runs}
        if any(code not in step.expect_exit for code in got.values()):
            out.append({"step": step.name, "recorded": sorted(step.expect_exit), **got})
    return out


def steps_without_files(steps: list[Step], out: Path) -> list[str]:
    """The steps whose output folder holds no file in either run."""
    def has_files(folder: Path) -> bool:
        return folder.is_dir() and any(p.is_file() for p in folder.rglob("*"))
    return [s.name for s in steps
            if not any(has_files(out / run / s.name) for run in ("run-a", "run-b"))]


def _log_diff(run_a: Path, run_b: Path) -> dict[str, dict]:
    """The command outputs of both runs, compared after replacing each run folder's name.
    A log in one run only is a difference."""
    def text(run: Path, name: str) -> str:
        t = (run / "_logs" / name).read_text(encoding="utf-8")
        return t.replace(run.as_posix(), "{run}").replace(str(run), "{run}")
    na = {p.name for p in (run_a / "_logs").glob("*.txt")}
    nb = {p.name for p in (run_b / "_logs").glob("*.txt")}
    out = {}
    for name in sorted(na | nb):
        if name not in na or name not in nb:
            out[name] = {"identical": False, "only_in": "run-a" if name in na else "run-b"}
            continue
        ta, tb = text(run_a, name), text(run_b, name)
        out[name] = ({"identical": True} if ta == tb else
                     {"identical": False, **_text_diff(ta.encode(), tb.encode())})
    return out


