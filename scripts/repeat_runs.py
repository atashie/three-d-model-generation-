def volatile_table(files: dict[str, dict]) -> list[dict]:
    """(record file name, JSON path with [*] for list indices) -> the files where it
    differs. `keys` is the same path as a list: a string is a dict key, ["*"] any index."""
    rows: dict[tuple[str, tuple], list[str]] = {}
    for rel, e in files.items():
        for k in e.get("json_keys", []):
            rows.setdefault((Path(rel).name, generalize_keys(tuple(k))), []).append(rel)
    return [{"record": rec, "path": render_path(keys),
             "keys": [list(k) if isinstance(k, tuple) else k for k in keys], "files": v}
            for (rec, keys), v in sorted(rows.items(), key=lambda r: (r[0][0],
                                                                       render_path(r[0][1])))]


def roadie_drop_hashes(out: Path) -> dict:
    drop = f"colored/{COLOR_JOBS[0]}/model.3mf"
    res = {}
    for name in ("run-a", "run-b"):
        f = out / name / drop
        if not f.is_file():
            res[name] = {"file": drop, "sha256": None, "status": "missing"}
            continue
        h = sha256_file(f)
        res[name] = {"file": drop, "sha256": h,
                     "status": "matches" if h == ROADIE_DROP_PRINTED_3MF else "differs"}
    return res


def write_report(out: Path, report: dict) -> None:
    (out / "report.json").write_text(json.dumps(report, indent=1, sort_keys=True) + "\n",
                                     encoding="utf-8")
    files = report["files"]
    same = [f for f, e in files.items() if e["identical"]]
    diff = [f for f, e in files.items() if not e["identical"]]
    lines = [f"# Repeat runs, {report['date']}", "",
             f"Machine: {report['machine']}", f"Command: `{report['command']}`",
             f"Mode: {report['mode']}", "",
             f"{len(files)} files; {len(same)} byte-identical; {len(diff)} differ.", "",
             (f"Unexpected exits: {len(report['unexpected_exits'])}. Steps that wrote no "
              f"files: {len(report['steps_without_files'])}."), ""]
    for u in report["unexpected_exits"]:
        lines.append(f"- UNEXPECTED: {u['step']}: recorded {u['recorded']}, "
                     f"run-a {u['run-a']}, run-b {u['run-b']}")
    for s in report["steps_without_files"]:
        lines.append(f"- NO FILES: {s}")
    if report["unexpected_exits"] or report["steps_without_files"]:
        lines.append("")
    lines += ["## Steps", "", "| step | exit run-a | exit run-b | recorded |",
              "|---|---|---|---|"]
    for a, b in zip(report["runs"]["run-a"], report["runs"]["run-b"]):
        lines.append(f"| {a['step']} | {a['exit']} | {b['exit']} | {a['expected_exit']} |")
    lines += ["", "## Files that differ", ""]
    for f in diff:
        e = files[f]
        lines.append(f"- `{f}`")
        if "only_in" in e:
            lines.append(f"  - only in {e['only_in']}")
        for p in e.get("json_paths", []):
            lines.append(f"  - `{p}`")
        if "text" in e:
            t = e["text"]
            counts = " (line counts differ)" if t["line_counts_differ"] else ""
            lines.append(f"  - {t['differing_lines']} of {t['lines_a']}/{t['lines_b']} lines "
                         f"differ{counts}; first:")
            for ex in t["examples"]:
                lines.append(f"    - line {ex['line']}: `{ex['a']}` / `{ex['b']}`")
        if "gcode" in e:
            g = e["gcode"]
            lines.append(f"  - G-code: timestamp line only: {g['timestamp_only']}; "
                         f"normalised SHA-256 equal: {g['normalised_equal']}")
        if "zip" in e:
            lines.append(f"  - members differ: {e['zip']['members_differ']}; metadata "
                         f"differ: {e['zip']['member_metadata_differ']}")
    lines += ["", "## JSON fields that differ", "", "| record | JSON path | files |",
              "|---|---|---|"]
    for row in report["volatile"]:
        lines.append(f"| {row['record']} | `{row['path']}` | {len(row['files'])} |")
    lines += ["", "## Command output (run folder name replaced)", ""]
    for name, e in report["logs"].items():
        state = "identical" if e["identical"] else (
            f"only in {e['only_in']}" if "only_in" in e else "differs")
        lines.append(f"- {name}: {state}")
    lines += ["", "## Roadie drop model.3mf against the printed file", ""]
    for run, h in report["roadie_drop_3mf"].items():
        lines.append(f"- {run}: {h['sha256']} - {h['status']} "
                     f"(printed: {ROADIE_DROP_PRINTED_3MF})")
    (out / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, required=True,
                    help="New folder; the runs go to OUT/run-a and OUT/run-b")
    ap.add_argument("--slicer-dir", type=Path, required=True, help="Pinned OrcaSlicer folder")
    ap.add_argument("--prusaslicer-dir", type=Path, required=True,
                    help="Pinned PrusaSlicer folder")
    ap.add_argument("--images-dir", type=Path, required=True,
                    help="Folder with the source images named in each selection.json")
    ap.add_argument("--records", type=Path, default=Path("artifacts"),
                    help="Folder holding the recorded runs (default artifacts)")
    ap.add_argument("--configs", type=Path, default=None,
                    help="Color configs folder (default RECORDS/colors-runs/configs)")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--plan-only", action="store_true",
                      help="Print the steps of one run and stop")
    mode.add_argument("--compare-only", action="store_true",
                      help="Run nothing: compare the existing OUT/run-a and OUT/run-b")
    ns = ap.parse_args(argv)
    configs = ns.configs or ns.records / "colors-runs" / "configs"
    try:
        steps, trace = plan_jobs(ns.records, configs, ns.images_dir, ns.slicer_dir,
                                 ns.prusaslicer_dir)
    except PlanError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    if ns.plan_only:
        for s in steps:
            print(f"{s.name}: {cmdline(['tdmg', *s.args])}  (exit {sorted(s.expect_exit)})")
        return 0
    if ns.compare_only:
        missing = [r for r in ("run-a", "run-b") if not (ns.out / r).is_dir()]
        if missing:
            print(f"error: {', '.join(str(ns.out / r) for r in missing)} not found",
                  file=sys.stderr)
            return 2
        runs = {name: runs_from_logs(steps, ns.out / name) for name in ("run-a", "run-b")}
    else:
        if ns.out.exists():
            print(f"error: {ns.out} exists; give a new folder", file=sys.stderr)
            return 2
        runs = {name: run_steps(steps, ns.out / name, Path.cwd())
                for name in ("run-a", "run-b")}
    files = compare_runs(ns.out / "run-a", ns.out / "run-b")
    report = {"date": time.strftime("%Y-%m-%d"),
              "machine": f"{platform.platform()} {platform.machine()} "
                         f"Python {platform.python_version()}",
              "command": cmdline(["python", "scripts/repeat_runs.py", *argv]),
              "mode": "compare-only (exit codes read from the run logs)" if ns.compare_only
                      else "run and compare",
              "trace": trace, "runs": runs, "files": files,
              "unexpected_exits": unexpected_exits(steps, runs),
              "steps_without_files": steps_without_files(steps, ns.out),
              "volatile": volatile_table(files),
              "logs": _log_diff(ns.out / "run-a", ns.out / "run-b"),
              "roadie_drop_3mf": roadie_drop_hashes(ns.out)}
    write_report(ns.out, report)
    same = sum(e["identical"] for e in files.values())
    bad = report["unexpected_exits"] or report["steps_without_files"]
    print(f"{len(files)} files; {same} byte-identical; {len(files) - same} differ; "
          f"{len(report['unexpected_exits'])} unexpected exits; "
          f"{len(report['steps_without_files'])} steps without files; "
          f"see {ns.out / 'report.md'}")
    for name, h in report["roadie_drop_3mf"].items():
        print(f"{name} roadie drop model.3mf {h['sha256']}: {h['status']} "
              "(against the printed file)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
