"""Run today's pipeline twice from the recorded inputs, then compare the two runs.

    uv run python scripts/repeat_runs.py --out artifacts/repeat-runs/2026-11-16 \\
        --slicer-dir artifacts/tools/orcaslicer-2.5.0 \\
        --prusaslicer-dir artifacts/tools/prusaslicer-2.9.7 \\
        --images-dir <folder with roadie.png and oddie.png>

A measurement script (restructure plan, Task 0). It does not change the pipeline.

**Inputs.** The jobs are the six slice runs in `artifacts/slice-runs/fd8/` (the two R1
models and the four owner color plans) and the calibration strip. The script follows
each slice record back to the records it was made from, by their recorded SHA-256:
slice.json -> flat.json or colored.json -> colors.json -> selection.json. Every
parameter comes from those records. A value that came from a rule is not passed, so
the run uses today's rule value (not checked against the recorded value). A parameter
that the records do not give, or a record that cannot be found or read, stops the
script before anything runs (PlanError, exit 2).

**Runs.** It drives the real CLI (`python -m tdmg.cli`, the code behind `tdmg`) into
OUT/run-a, then OUT/run-b. Each command's output and exit code are kept in
RUN/_logs/. `--compare-only` skips the runs and compares the existing OUT/run-a and
OUT/run-b, reading the exit codes back from those logs.

**Comparison.** For every file in either run: present in both, byte-identical or not.
For a JSON file that differs, the JSON paths that differ (keys with '.', '/', '[', ']'
or '"' are bracket-quoted: `$.outputs["plate_1.gcode"]`). For a text file, the number
of lines that differ and the first few. For a G-code file, whether only the slicer's
timestamp line differs. For a zip (3MF), the members that differ. The result goes to
OUT/report.json and OUT/report.md. The exit code is 1 when a step exited otherwise
than on the recorded run, or wrote no files in either run.
"""

