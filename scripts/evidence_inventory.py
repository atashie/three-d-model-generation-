"""List every tracked reference to the research records, grouped by record.

    uv run python scripts/evidence_inventory.py          # write docs/design/evidence-inventory.md
    uv run python scripts/evidence_inventory.py --check  # exit 1 if that file is stale

Task 1 of docs/plans/2026-11-16-restructure.md. A record is one folder under
research/verification/, research/reviews/ or research/experiments/, one file under
docs/plans/ or reports/, or one entry under research_notes/. A record is "cited" when a
rule, test, profile, code, script or CI file refers to it; otherwise it is "uncited".

What counts as a reference (each is tested in tests/test_evidence_inventory.py):
- a plain path, with / or \\ separators, %20 for spaces, or real spaces when the name
  is one of the records in the tree;
- a Markdown link, resolved against the linking file's folder;
- a Python path built from string literals (ROOT / "research" / "verification" / "x");
- a path broken over two lines (the second line's comment marker is skipped), when the
  joined text names a record in the tree.
A built path that stops at a root folder, and a path that names no record in the tree,
are listed as unresolved, not dropped. Binary files (with a NUL byte) are skipped; text
that is not UTF-8 is listed. The output file, this script and its test are not scanned.
"""

from __future__ import annotations

import posixpath
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import unquote

OUTPUT = "docs/design/evidence-inventory.md"
# The output, this script and its test name records as data, not as citations.
NOT_SCANNED = frozenset({OUTPUT, "scripts/evidence_inventory.py",
                         "tests/test_evidence_inventory.py"})
HEADER = ("<!-- GENERATED by scripts/evidence_inventory.py from the tracked files (git ls-files). "
          "Do not edit by hand. -->\n\n")

# Root folders, longest first so research/verification wins over research.
ROOTS = ("research/verification", "research/reviews", "research/experiments", "research_notes",
         "research", "docs/plans", "reports")
# Roots whose records are their direct children.
UNIT_ROOTS = ("research/verification", "research/reviews", "research/experiments",
              "research_notes", "docs/plans", "reports")
CITING = ("rule", "test", "profile", "code", "script", "CI")
CATEGORIES = (*CITING, "doc", "status", "record", "config")
KEPT_IN_PLACE = ("research_notes", "reports")   # design section 6; CLAUDE.md rule 6
ACTIVE = ("docs/plans/2026-11-16-restructure-design.md", "docs/plans/2026-11-16-restructure.md",
          "research/reviews/2026-11-16-restructure-design",
          "research/verification/2026-11-16-repeatability")

_ROOT_ALT = "|".join(r.replace("/", r"[/\\]") for r in ROOTS)
# A root at the start of a path: not preceded by a path character, unless by ./ or ../
PLAIN = re.compile(rf"(?<![\w.\\/-])((?:\.\.?/)*)(?:{_ROOT_ALT})(?![\w-])")
PATH_CHARS = re.compile(r"[\w./\\%+=@~*-]*")   # * keeps a glob visible in the output
MD_LINK = re.compile(r"\]\(\s*(<[^>\n]+>|[^)\s]+)")
MD_REFDEF = re.compile(r"^\s*\[[^\]]+\]:\s*(<[^>\n]+>|\S+)")
STR_LIT = r"(?:\"[^\"\n]*\"|'[^'\n]*')"
CHAIN = re.compile(rf"(?:Path\(\s*{STR_LIT}\s*\)|(?<=[\w)\]])\s*/\s*{STR_LIT})"
                   rf"(?:\s*/\s*{STR_LIT})*")
LIT = re.compile(STR_LIT)
QUOTED_ROOT = re.compile(rf"[\"']((?:{_ROOT_ALT})/?)[\"']")
CONTINUATION = re.compile(r"^\s*(?:#+|//+|\*|>|[\"'])?\s*")


@dataclass(frozen=True, order=True)
class Ref:
    file: str
    line: int
    category: str


@dataclass(frozen=True, order=True)
class Unresolved:
    file: str
    line: int
    text: str
    reason: str


@dataclass
class Inventory:
    refs: dict[str, set[Ref]] = field(default_factory=lambda: defaultdict(set))
    root_refs: dict[str, set[Ref]] = field(default_factory=lambda: defaultdict(set))
    unresolved: list[Unresolved] = field(default_factory=list)
    undecodable: list[str] = field(default_factory=list)


def category(path: str) -> str:
    if path == "docs/STATUS.md":
        return "status"
    for prefix, cat in (("research/", "record"), ("research_notes/", "record"),
                        ("reports/", "record"), ("docs/plans/", "record"), ("rules/", "rule"),
                        ("tests/", "test"), ("profiles/", "profile"), ("src/", "code"),
                        ("scripts/", "script"), (".github/", "CI"), ("docs/", "doc")):
        if path.startswith(prefix):
            return cat
    return "doc" if path.endswith(".md") else "config"


def unit_of(path: str) -> str | None:
    """The record a repo-relative path belongs to, or None if it is not under a root."""
    for root in UNIT_ROOTS:
        if path.startswith(root + "/"):
            name = path[len(root) + 1:].split("/")[0]
            return f"{root}/{name}" if name else None
    return None


def root_of(path: str) -> str | None:
    p = path.rstrip("/")
    return p if p in ROOTS else None


def units_in(files: list[str]) -> list[str]:
    return sorted({u for f in files if (u := unit_of(f))})


def _read(root: Path, rel: str, inv: Inventory) -> list[str] | None:
    data = (root / rel).read_bytes()
    if b"\x00" in data[:8192]:
        return None
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        inv.undecodable.append(rel)
        return None
    return [line.removesuffix("\r") for line in text.split("\n")]


def _norm(text: str) -> str:
    return text.replace("\\\\", "/").replace("\\", "/").replace("%20", " ")


class _Scanner:
    def __init__(self, units: list[str]):
        self.units = set(units)
        # Record names per root, longest first, for names with spaces.
        self.names: dict[str, list[str]] = defaultdict(list)
        for u in sorted(units, key=len, reverse=True):
            root = next(r for r in UNIT_ROOTS if u.startswith(r + "/"))
            self.names[root].append(u[len(root) + 1:])

    def match(self, text: str) -> tuple[str, str]:
        """Classify a normalised path text that starts at a root.

        Returns (kind, value): ("unit", unit), ("root", root) or ("missing", path)."""
        for root in ROOTS:
            if text.startswith(root) and (len(text) == len(root) or text[len(root)] != "_"):
                break
        rest = text[len(root):]
        if root in UNIT_ROOTS and rest.startswith("/"):
            for name in self.names[root]:
                after = rest[1 + len(name):1 + len(name) + 1]
                if rest[1:].startswith(name) and (after == "" or not re.match(r"[\w-]", after)):
                    return "unit", f"{root}/{name}"
        token = (root + PATH_CHARS.match(rest).group(0)).rstrip(".,;:")
        if root_of(token) or root_of(token.rstrip("/")):
            return "root", token.rstrip("/")
        # research/<x> where x is not verification, reviews or experiments, or a missing record
        unit = unit_of(token)
        if unit in self.units:
            return "unit", unit
        return "missing", token


def _targets(rel: str, lines: list[str], i: int, scanner: _Scanner):
    """Yield (kind, value, text) for line i of file rel."""
    line = _norm(lines[i])
    here = posixpath.dirname(rel)
    for m in PLAIN.finditer(line):
        start = m.start() + len(m.group(1))
        text = line[start:]
        kind, value = scanner.match(text)
        token_end = start + len(PATH_CHARS.match(line, start).group(0))
        if "/" not in line[start:token_end]:
            continue   # the bare word "research", not a path
        truncated = line[token_end:].strip() == "" and line[token_end - 1:token_end] in "/-"
        if kind != "unit" and truncated and i + 1 < len(lines):
            nxt = _norm(lines[i + 1])
            joined = line[start:token_end] + nxt[CONTINUATION.match(nxt).end():]
            jkind, jvalue = scanner.match(joined)
            if jkind == "unit":
                kind, value = jkind, jvalue
        if m.group(1):   # ./ or ../ prefix: resolve against the file's folder
            base = posixpath.normpath(posixpath.join(here, m.group(1)))
            resolved = text if base == "." else f"{base}/{text}"
            if not any(resolved.startswith(r) for r in ROOTS):
                continue
            kind, value = scanner.match(resolved)
        yield kind, value, value if kind == "missing" else line[m.start():token_end]
    if rel.endswith(".md"):
        for target in MD_LINK.findall(lines[i]) + MD_REFDEF.findall(lines[i]):
            target = _norm(unquote(target.strip("<>"))).split("#")[0]
            if not target or re.match(r"[a-z]+:", target) or target.startswith("/"):
                continue
            resolved = posixpath.normpath(posixpath.join(here, target))
            if any(resolved == r or resolved.startswith(r + "/") for r in ROOTS):
                kind, value = scanner.match(resolved)
                yield kind, value, value if kind == "missing" else target
    if rel.endswith(".py"):
        for m in CHAIN.finditer(lines[i]):
            path = "/".join(s[1:-1] for s in LIT.findall(m.group(0)))
            if not any(path == r or path.startswith(r + "/") for r in ROOTS):
                continue
            kind, value = scanner.match(path)
            if kind == "root":
                kind, value = "constructed", path
            yield kind, value, m.group(0).strip().lstrip("/").strip()
    else:
        for m in QUOTED_ROOT.finditer(line):
            yield "root", m.group(1).rstrip("/"), m.group(0)


def scan(root: Path, files: list[str]) -> Inventory:
    inv = Inventory()
    scanner = _Scanner(units_in(files))
    for rel in files:
        if rel in NOT_SCANNED:
            continue
        lines = _read(root, rel, inv)
        if lines is None:
            continue
        own, cat = unit_of(rel), category(rel)
        for i in range(len(lines)):
            for kind, value, text in _targets(rel, lines, i, scanner):
                ref = Ref(rel, i + 1, cat)
                if kind == "unit" and value != own:
                    inv.refs[value].add(ref)
                elif kind == "root":
                    inv.root_refs[value].add(ref)
                elif kind == "missing":
                    inv.unresolved.append(Unresolved(rel, i + 1, text,
                                                     "names no record in the tree"))
                elif kind == "constructed":
                    inv.unresolved.append(Unresolved(
                        rel, i + 1, text, f"constructed path stops at {value}/; the code adds "
                        "the rest at run time"))
    inv.unresolved = sorted(set(inv.unresolved))
    inv.undecodable.sort()
    return inv


def status(unit: str, inv: Inventory) -> str:
    refs = inv.refs.get(unit, set())
    if any(r.category in CITING for r in refs):
        return "cited"
    return "uncited" if refs else "uncited, no references"


def _note(unit: str) -> str:
    notes = []
    if unit.split("/")[0] in KEPT_IN_PLACE:
        notes.append("kept in place (design section 6)")
    if unit in ACTIVE:
        notes.append("active work, stays where it is")
    return "; ".join(notes)


def _counts(refs: set[Ref]) -> list[str]:
    return [str(sum(r.category == c for r in refs) or "") for c in CATEGORIES]


def _where(refs: set[Ref]) -> list[str]:
    by_file: dict[str, list[int]] = defaultdict(list)
    for r in sorted(refs):
        by_file[r.file].append(r.line)
    return [f"- `{f}` ({category(f)}): lines {', '.join(map(str, ls))}"
            for f, ls in sorted(by_file.items())]


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("`", "")


def _lines(items: list[str], empty: str) -> list[str]:
    return [i + "\n" for i in items] if items else [empty + "\n"]


INTRO = (
    "Which research records the repository points at, and from where. It is a snapshot for "
    "the restructure (Task 1 of `docs/plans/2026-11-16-restructure.md`); line numbers move as "
    "files change, so regenerate it before you use it.\n\n"
    "A record is one folder under `research/verification/`, `research/reviews/` or "
    "`research/experiments/`, one file under `docs/plans/` or `reports/`, or one entry under "
    "`research_notes/`. A record is **cited** when a rule, test, profile, code, script or CI "
    "file refers to it. It is **uncited** when only docs, `docs/STATUS.md`, config files or "
    "other records refer to it, or nothing does. A record's references to itself are not "
    "counted. The counts are referring lines.\n\n")


def render(inv: Inventory, units: list[str]) -> str:
    groups = {s: [u for u in units if status(u, inv) == s]
              for s in ("cited", "uncited", "uncited, no references")}
    out = [HEADER, "# Evidence inventory\n\n", INTRO,
           (f"Records: {len(units)}. Cited: {len(groups['cited'])}. Uncited: "
           f"{len(groups['uncited'])}. Uncited with no references: "
           f"{len(groups['uncited, no references'])}.\n\n"),
           "## Summary\n\n",
           "| Record | Status | Note | " + " | ".join(CATEGORIES) + " |\n",
           "|---|---|---|" + "---|" * len(CATEGORIES) + "\n"]
    for s, members in groups.items():
        for u in members:
            refs = inv.refs.get(u, set())
            out.append(f"| `{_cell(u)}` | {s} | {_note(u)} | " + " | ".join(_counts(refs)) + " |\n")
    titles = {"cited": "Cited records", "uncited": "Uncited records (referred to only by docs, "
              "status, config or other records)", "uncited, no references":
              "Records nothing refers to"}
    for s, members in groups.items():
        out.append(f"\n## {titles[s]}\n")
        if not members:
            out.append("\nNone.\n")
        for u in members:
            note = _note(u)
            out.append(f"\n### `{_cell(u)}`\n\n" + (f"{note[0].upper()}{note[1:]}.\n\n" if note
                                                     else ""))
            refs = inv.refs.get(u, set())
            out.extend(_lines(_where(refs), "No references."))
    out.append("\n## References to a root folder\n\n"
               "A mention of a whole folder, such as `research/reviews/`, not one record.\n")
    for root in sorted(inv.root_refs):
        out.append(f"\n### `{root}`\n\n")
        out.extend(line + "\n" for line in _where(inv.root_refs[root]))
    out.append("\n## Unresolved references\n\n"
               "References this script could not tie to one record: a built path that stops at "
               "a root folder, or a path that names no record in the tree (a placeholder, a "
               "pattern, a record that does not exist, or a name broken over lines).\n\n")
    if inv.unresolved:
        out.append("| File | Line | Text | Why |\n|---|---|---|---|\n")
        out.extend(f"| `{_cell(u.file)}` | {u.line} | `{_cell(u.text)}` | {u.reason} |\n"
                   for u in inv.unresolved)
    else:
        out.append("None.\n")
    out.append("\n## Files that are not UTF-8 text\n\n")
    out.extend(_lines([f"- `{f}`" for f in inv.undecodable], "None."))
    return "".join(out)


def tracked_files(root: Path) -> list[str]:
    out = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True)
    return sorted(f for f in out.stdout.decode("utf-8").split("\0") if f)


def main(argv: list[str]) -> int:
    root = Path(__file__).resolve().parents[1]
    files = tracked_files(root)
    text = render(scan(root, files), units_in(files))
    path = root / OUTPUT
    if "--check" in argv:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            print(f"stale: {OUTPUT} (run: uv run python scripts/evidence_inventory.py)")
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
