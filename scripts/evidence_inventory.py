def render(inv: Inventory, units: list[str]) -> str:
    groups = {s: [u for u in units if status(u, inv) == s] for s in STATUSES}
    n_cited = sum(len(groups[s]) for s in STATUSES[:3])
    out = [HEADER, "# Evidence inventory\n\n", INTRO,
           (f"Records: {len(units)}. Counted as cited: {n_cited} ({len(groups['cited'])} by "
            f"path, {len(groups['cited by name'])} by name only, "
            f"{len(groups['possibly cited (ambiguous name)'])} by an ambiguous name only). "
            f"Uncited: {len(groups['uncited'])}. Uncited with no references: "
            f"{len(groups['uncited, no references'])}.\n\n"),
           "## Summary\n\n",
           ("| Record | Status | Note | Linked from docs | Linked from kept records | "
            + " | ".join(CATEGORIES) + " |\n"),
           "|---|---|---|---|---|" + "---|" * len(CATEGORIES) + "\n"]
    kept = kept_units(inv, units)
    for s, members in groups.items():
        for u in members:
            refs = inv.refs.get(u, set())
            out.append(f"| `{_cell(u)}` | {s} | {_note(u)} | {linked_from_docs(u, inv)} | "
                       f"{len(linked_from_kept(u, inv, units, kept)) or ''} | "
                       + " | ".join(_counts(refs)) + " |\n")
    titles = {"cited": "Cited records (by path)",
              "cited by name": "Records cited by name only",
              "possibly cited (ambiguous name)": "Records possibly cited by an ambiguous name",
              "uncited": "Uncited records (referred to only by docs, status, config or other "
                         "records)",
              "uncited, no references": "Records nothing refers to"}
    for s, members in groups.items():
        out.append(f"\n## {titles[s]}\n")
        if not members:
            out.append("\nNone.\n")
        for u in members:
            note = _note(u)
            out.append(f"\n### `{_cell(u)}`\n\n" + (f"{note[0].upper()}{note[1:]}.\n\n" if note
                                                     else ""))
            refs = inv.refs.get(u, set())
            out.extend(_lines(_where(refs), "No references."))
            if linked := linked_from_kept(u, inv, units, kept):
                out.append("\nLinked from kept records: "
                           + ", ".join(f"`{_cell(o)}`" for o in linked) + ".\n")
    out.append("\n## References to a root folder\n\n"
               "A mention of a whole folder, such as `research/reviews/`, not one record.\n")
    for root in sorted(inv.root_refs):
        out.append(f"\n### `{root}`\n\n")
        out.extend(line + "\n" for line in _where(inv.root_refs[root]))
    out.append("\n## Ambiguous name citations\n\n"
               "A machine-read file names a review by a date that several review folders "
               "share. Every candidate is counted as possibly cited.\n\n")
    if inv.ambiguous:
        out.append("| File | Line | Text | Candidates |\n|---|---|---|---|\n")
        out.extend(f"| `{_cell(a.file)}` | {a.line} | `{_cell(a.text)}` | "
                   f"{', '.join(f'`{c}`' for c in a.candidates)} |\n" for a in inv.ambiguous)
    else:
        out.append("None.\n")
    out.append("\n## Review mentions not tied to a record\n\n"
               "A machine-read file mentions a review with no date and no review path on the "
               "same line, or a review that has no record folder. Read these by hand.\n\n")
    if inv.unattributed:
        out.append("| File | Line | Text | Why |\n|---|---|---|---|\n")
        out.extend(f"| `{_cell(u.file)}` | {u.line} | `{_cell(u.text)}` | {u.reason} |\n"
                   for u in inv.unattributed)
    else:
        out.append("None.\n")
    out.append("\n## Unparsed mentions\n\n"
               "A line in a machine-read file that puts a root word (research, reports, "
               "research_notes, plans) beside a quote, slash or backslash but gave no reference "
               "this script reads, for example a path built at run time. Read these by hand.\n\n")
    if inv.unparsed:
        out.append("| File | Line | Text |\n|---|---|---|\n")
        out.extend(f"| `{_cell(u.file)}` | {u.line} | `{_cell(u.text)}` |\n"
                   for u in inv.unparsed)
    else:
        out.append("None.\n")
    out.append("\n## Glob matches\n\n"
               "A path pattern with `*`, expanded to the records it matches. Each match is "
               "counted as a reference from that file.\n\n")
    if inv.globs:
        out.append("| File | Line | Pattern | Matches |\n|---|---|---|---|\n")
        out.extend(f"| `{_cell(g.file)}` | {g.line} | `{_cell(g.text)}` | "
                   f"{', '.join(f'`{c}`' for c in g.candidates)} |\n" for g in inv.globs)
    else:
        out.append("None.\n")
    out.append("\n## Unresolved references\n\n"
               "References this script could not tie to one record: a built path that stops at "
               "a root folder, a `./` or `../` path that resolves outside the record folders, "
               "or a path that names no record in the tree (a placeholder, a pattern, a record "
               "that does not exist, or a name broken over lines).\n\n")
    if inv.unresolved:
        out.append("| File | Line | Text | Why |\n|---|---|---|---|\n")
        out.extend(f"| `{_cell(u.file)}` | {u.line} | `{_cell(u.text)}` | {u.reason} |\n"
                   for u in inv.unresolved)
    else:
        out.append("None.\n")
    out.append("\n## Files that are not UTF-8 text\n\n")
    out.extend(_lines([f"- `{f}`" for f in inv.undecodable], "None."))
    return "".join(out)


def tracked_files(root: Path) -> list[str]:
    out = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True)
    return sorted(f for f in out.stdout.decode("utf-8").split("\0") if f)


def main(argv: list[str], root: Path | None = None) -> int:
    root = Path(__file__).resolve().parents[1] if root is None else root
    files = tracked_files(root)
    text = render(scan(root, files), units_in(files))
    path = root / OUTPUT
    if "--check" in argv:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            print(f"stale: {OUTPUT} (run: uv run python scripts/evidence_inventory.py)")
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
