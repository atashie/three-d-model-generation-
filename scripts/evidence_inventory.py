"""List every tracked reference to the research records, grouped by record.

    uv run python scripts/evidence_inventory.py          # write docs/design/evidence-inventory.md
    uv run python scripts/evidence_inventory.py --check  # exit 1 if that file is stale

Task 1 of docs/plans/2026-11-16-restructure.md. A record is one folder under
research/verification/, research/reviews/ or research/experiments/, one file under
docs/plans/ or reports/, or one entry under research_notes/. A record is "cited" when a
rule, test, profile, code, script or CI file refers to it; otherwise it is "uncited".

What counts as a reference (each is tested in tests/test_evidence_inventory.py):
- a plain path, with / or \\ separators, %20 for spaces, or real spaces when the name
  is one of the records in the tree;
- a Markdown link, resolved against the linking file's folder;
- a Python path built from string literals (ROOT / "research" / "verification" / "x");
- a path broken over two lines (the second line's comment marker is skipped), when the
  joined text names a record in the tree;
- a glob (research/verification/2026-11-10-*), expanded to the records it matches;
- in machine-read files only (rule, test, profile, code, script, CI, .toml/.yaml config):
  a review named by date without a path, "Codex review 2026-11-14". A date that several
  review folders share is listed as ambiguous and counts for all of them. A numbered name
  ("Codex review 3") is tied to a record only by a path on the same line; without one it
  is listed for reading by hand.
A built path that stops at a root folder, and a path that names no record in the tree,
are listed as unresolved, not dropped. Binary files (with a NUL byte) are skipped; text
that is not UTF-8 is listed. The output file, this script and its test are not scanned.
"""

from __future__ import annotations

import posixpath
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from fnmatch import fnmatchcase
from pathlib import Path
from urllib.parse import unquote

OUTPUT = "docs/design/evidence-inventory.md"
# The output, this script and its test name records as data, not as citations.
NOT_SCANNED = frozenset({OUTPUT, "scripts/evidence_inventory.py",
                         "tests/test_evidence_inventory.py"})
HEADER = ("<!-- GENERATED by scripts/evidence_inventory.py from the tracked files (git ls-files). "
          "Do not edit by hand. -->\n\n")

# Root folders, longest first so research/verification wins over research.
ROOTS = ("research/verification", "research/reviews", "research/experiments", "research_notes",
         "research", "docs/plans", "reports")
# Roots whose records are their direct children.
UNIT_ROOTS = ("research/verification", "research/reviews", "research/experiments",
              "research_notes", "docs/plans", "reports")
CITING = ("rule", "test", "profile", "code", "script", "CI", "config-citing")
CATEGORIES = (*CITING, "doc", "status", "record", "config")
KEPT_IN_PLACE = ("research_notes", "reports")   # design section 6; CLAUDE.md rule 6
ACTIVE = ("docs/plans/2026-11-16-restructure-design.md", "docs/plans/2026-11-16-restructure.md",
          "research/reviews/2026-11-16-restructure-design",
          "research/verification/2026-11-16-repeatability")

_ROOT_ALT = "|".join(r.replace("/", r"[/\\]") for r in ROOTS)
# A root at the start of a path: not preceded by a path character, unless by ./ or ../
PLAIN = re.compile(rf"(?<![\w.\\/-])((?:\.\.?/)*)(?:{_ROOT_ALT})(?![\w-])")
PATH_CHARS = re.compile(r"[\w./\\%+=@~*-]*")   # * keeps a glob visible in the output
MD_LINK = re.compile(r"\]\(\s*(<[^>\n]+>|[^)\s]+)")
MD_REFDEF = re.compile(r"^\s*\[[^\]]+\]:\s*(<[^>\n]+>|\S+)")
STR_LIT = r"(?:\"[^\"\n]*\"|'[^'\n]*')"
CHAIN = re.compile(rf"(?:Path\(\s*{STR_LIT}\s*\)|(?<=[\w)\]])\s*/\s*{STR_LIT})"
                   rf"(?:\s*/\s*{STR_LIT})*")
LIT = re.compile(STR_LIT)
QUOTED_ROOT = re.compile(rf"[\"']((?:{_ROOT_ALT})/?)[\"']")
CONTINUATION = re.compile(r"^\s*(?:#+|//+|\*|>|[\"'])?\s*")


# Review names. A numbered name ("Codex review 3") says nothing about its folder, so it is
# tied to a record only by a path written on the same line (Task 2 of
# docs/plans/2026-11-16-restructure.md wrote one beside every numbered citation in code and
# tests). A dated name ("Codex review 2026-11-14") maps to the one review folder of that
# date; when several share it, it is listed as ambiguous, not guessed.
CODEX = re.compile(r"\bCodex\b")
NUMBERED = re.compile(r"Codex(?: review)? (\d+)(?![\d-])")
DATE = re.compile(r"(?<![\w/-])(\d{4}-\d{2}-\d{2})(?![\w-])")   # not inside a path or name
DATE_AFTER, DATE_BEFORE = 60, 40   # characters searched for a date beside "Codex"
OTHER_REVIEW = re.compile(r"\b[Rr]eview (?:[NP]\d+|of )")   # named reviews with no folder
# Safety net: a root word beside a quote, / or \ on a line that gave no reference
# ($ROOT/research/..., os.path.join(ROOT, "research"), "Research", joinpath("plans")).
_WORD = r"(?:research_notes|research|reports|plans)"
MENTION = re.compile(rf"(?i)[\"'/\\]\s*{_WORD}\b|\b{_WORD}\s*[\"'/\\]")


@dataclass(frozen=True, order=True)
class Ref:
    file: str
    line: int
    category: str
    how: str = "path"   # path, glob, name or ambiguous name


@dataclass(frozen=True, order=True)
class Unresolved:
    file: str
    line: int
    text: str
    reason: str


@dataclass(frozen=True, order=True)
class Ambiguous:
    file: str
    line: int
    text: str
    candidates: tuple[str, ...]


@dataclass
class Inventory:
    refs: dict[str, set[Ref]] = field(default_factory=lambda: defaultdict(set))
    root_refs: dict[str, set[Ref]] = field(default_factory=lambda: defaultdict(set))
    unresolved: list[Unresolved] = field(default_factory=list)
    ambiguous: list[Ambiguous] = field(default_factory=list)
    unattributed: list[Unresolved] = field(default_factory=list)
    globs: list[Ambiguous] = field(default_factory=list)
    unparsed: list[Unresolved] = field(default_factory=list)
    undecodable: list[str] = field(default_factory=list)


def category(path: str) -> str:
    if path == "docs/STATUS.md":
        return "status"
    for prefix, cat in (("research/", "record"), ("research_notes/", "record"),
                        ("reports/", "record"), ("docs/plans/", "record"), ("rules/", "rule"),
                        ("tests/", "test"), ("profiles/", "profile"), ("src/", "code"),
                        ("scripts/", "script"), (".github/", "CI"), ("docs/", "doc")):
        if path.startswith(prefix):
            return cat
    # Outside the known folders: a program or a machine-read config can cite a record too.
    suffix = posixpath.splitext(path)[1]
    if suffix in (".py", ".sh", ".ps1"):
        return "code"
    if suffix in (".yaml", ".yml", ".toml"):
        return "config-citing"
    return "doc" if suffix == ".md" else "config"


def unit_of(path: str) -> str | None:
    """The record a repo-relative path belongs to, or None if it is not under a root."""
    for root in UNIT_ROOTS:
        if path.startswith(root + "/"):
            name = path[len(root) + 1:].split("/")[0]
            return f"{root}/{name}" if name else None
    return None


def root_of(path: str) -> str | None:
    p = path.rstrip("/")
    return p if p in ROOTS else None


def units_in(files: list[str]) -> list[str]:
    return sorted({u for f in files if (u := unit_of(f))})


def _read(root: Path, rel: str, inv: Inventory) -> list[str] | None:
    try:
        data = (root / rel).read_bytes()
    except FileNotFoundError:
        raise SystemExit(f"evidence_inventory: {rel} is tracked by git but missing on disk; "
                         "restore it or remove it from the index, then run again") from None
    if b"\x00" in data[:8192]:
        return None
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        inv.undecodable.append(rel)
        return None
    return [line.removesuffix("\r") for line in text.split("\n")]


def _norm(text: str) -> str:
    return text.replace("\\\\", "/").replace("\\", "/").replace("%20", " ")


def _root_at(text: str) -> str | None:
    """The root folder that text starts with (longest first), or None."""
    for root in ROOTS:
        if text.startswith(root) and not re.match(r"[\w-]", text[len(root):len(root) + 1]):
            return root
    return None


class _Scanner:
    def __init__(self, units: list[str]):
        self.units = set(units)
        # Record names per root, longest first, for names with spaces.
        self.names: dict[str, list[str]] = defaultdict(list)
        for u in sorted(units, key=len, reverse=True):
            root = next(r for r in UNIT_ROOTS if u.startswith(r + "/"))
            self.names[root].append(u[len(root) + 1:])

    def match(self, text: str) -> tuple[str, str]:
        """Classify a normalised path text that starts at a root.

        Returns (kind, value): ("unit", unit), ("root", root), ("glob", (pattern, units))
        or ("missing", path)."""
        root = _root_at(text)
        if root is None:
            return "missing", PATH_CHARS.match(text).group(0)
        rest = text[len(root):]
        if root in UNIT_ROOTS and rest.startswith("/"):
            for name in self.names[root]:
                after = rest[1 + len(name):1 + len(name) + 1]
                if rest[1:].startswith(name) and (after == "" or not re.match(r"[\w-]", after)):
                    return "unit", f"{root}/{name}"
        token = (root + PATH_CHARS.match(rest).group(0)).rstrip(".,;:")
        if "*" in token:
            pattern = unit_of(token) or token
            matches = tuple(u for u in sorted(self.units) if fnmatchcase(u, pattern))
            if matches:
                return "glob", (token, matches)
        if root_of(token) or root_of(token.rstrip("/")):
            return "root", token.rstrip("/")
        # research/<x> where x is not verification, reviews or experiments, or a missing record
        unit = unit_of(token)
        if unit in self.units:
            return "unit", unit
        return "missing", token


def _plain_path(rel: str, prefix: str, text: str) -> str | None:
    """The repo-relative form of a plain path: text, after prefix (./ or ../ parts).

    With no prefix the path is from the repo root. With one, a Markdown file's path is
    relative to the file's folder (as its links are); any other file's is tried from the
    repo root first (as rules refs and profile records are), then from the file's folder.
    None if no reading lands under a root folder."""
    if not prefix:
        return text
    bases = [posixpath.dirname(rel)] if rel.endswith(".md") else ["", posixpath.dirname(rel)]
    for here in bases:
        base = posixpath.normpath(posixpath.join(here, prefix)) if here or prefix else "."
        if base == ".." or base.startswith("../"):
            continue
        path = text if base == "." else f"{base}/{text}"
        if _root_at(path):
            return path
    return None


def _targets(rel: str, lines: list[str], i: int, scanner: _Scanner):
    """Yield (kind, value, text) for line i of file rel."""
    line = _norm(lines[i])
    here = posixpath.dirname(rel)
    for m in PLAIN.finditer(line):
        start = m.start() + len(m.group(1))
        token_end = start + len(PATH_CHARS.match(line, start).group(0))
        if "/" not in line[start:token_end]:
            continue   # the bare word "research", not a path
        written = line[m.start():token_end].strip()
        path = _plain_path(rel, m.group(1), line[start:])
        if path is None:
            base = posixpath.normpath(posixpath.join(here, m.group(1)))
            where = "the tree" if base == ".." or base.startswith("../") else "the record folders"
            yield "outside", f"relative path resolves outside {where}", written
            continue
        kind, value = scanner.match(path)
        truncated = line[token_end:].strip() == "" and line[token_end - 1:token_end] in "/-"
        if kind != "unit" and truncated and i + 1 < len(lines):
            nxt = _norm(lines[i + 1])
            cut = len(path) - (len(line) - token_end)   # the token's end inside path
            jkind, jvalue = scanner.match(path[:cut] + nxt[CONTINUATION.match(nxt).end():])
            if jkind == "unit":
                kind, value = jkind, jvalue
        yield kind, value, value if kind == "missing" else written
    if rel.endswith(".md"):
        for target in MD_LINK.findall(lines[i]) + MD_REFDEF.findall(lines[i]):
            target = _norm(unquote(target.strip("<>"))).split("#")[0]
            if not target or re.match(r"[a-z]+:", target) or target.startswith("/"):
                continue
            resolved = posixpath.normpath(posixpath.join(here, target))
            if any(resolved == r or resolved.startswith(r + "/") for r in ROOTS):
                kind, value = scanner.match(resolved)
                yield kind, value, value if kind == "missing" else target
    if rel.endswith(".py"):
        for m in CHAIN.finditer(lines[i]):
            path = "/".join(s[1:-1] for s in LIT.findall(m.group(0)))
            if not any(path == r or path.startswith(r + "/") for r in ROOTS):
                continue
            kind, value = scanner.match(path)
            if kind == "root":
                kind, value = "constructed", path
            yield kind, value, m.group(0).strip().lstrip("/").strip()
    else:
        for m in QUOTED_ROOT.finditer(line):
            yield "root", m.group(1).rstrip("/"), m.group(0)


def _names(lines: list[str], i: int, reviews: list[str]):
    """Yield (kind, value, text) for each review named on line i: ("name", unit),
    ("ambiguous", candidates) or ("unattributed", reason). A name broken onto the next
    line is joined to it."""
    line = lines[i]
    text = line
    if i + 1 < len(lines):
        text += " " + lines[i + 1][CONTINUATION.match(lines[i + 1]).end():]
    for m in CODEX.finditer(text):
        if m.start() >= len(line):
            break
        snippet = text[m.start():m.start() + 40].strip()
        n = NUMBERED.match(text, m.start())
        if n:
            yield "unattributed", f"review number {n.group(1)}, which names no folder", snippet
            continue
        dates = DATE.findall(text[m.end():m.end() + DATE_AFTER]) or DATE.findall(
            text[max(0, m.start() - DATE_BEFORE):m.start()])[-1:]
        if not dates:
            yield "unattributed", "no review number or date", snippet
            continue
        candidates = tuple(u for u in reviews if u.split("/")[-1].startswith(dates[0] + "-"))
        if len(candidates) == 1:
            yield "name", candidates[0], snippet
        elif candidates:
            yield "ambiguous", candidates, snippet
        else:
            yield "unattributed", f"no review folder dated {dates[0]}", snippet
    for m in OTHER_REVIEW.finditer(line):
        yield "unattributed", "a named review with no record folder", line[m.start():][:40]


def scan(root: Path, files: list[str]) -> Inventory:
    inv = Inventory()
    units = units_in(files)
    scanner = _Scanner(units)
    reviews = [u for u in units if u.startswith("research/reviews/")]
    for rel in files:
        if rel in NOT_SCANNED:
            continue
        lines = _read(root, rel, inv)
        if lines is None:
            continue
        own, cat = unit_of(rel), category(rel)
        for i in range(len(lines)):
            reviews_by_path = set()   # review records named by path on this line
            found = False             # any target at all, on this line
            for kind, value, text in _targets(rel, lines, i, scanner):
                found = True
                if kind == "unit" and value.startswith("research/reviews/"):
                    reviews_by_path.add(value)
                ref = Ref(rel, i + 1, cat)
                if kind == "unit" and value != own:
                    inv.refs[value].add(ref)
                elif kind == "root":
                    inv.root_refs[value].add(ref)
                elif kind == "missing":
                    inv.unresolved.append(Unresolved(rel, i + 1, text,
                                                     "names no record in the tree"))
                elif kind == "glob":
                    pattern, matches = value
                    inv.globs.append(Ambiguous(rel, i + 1, pattern, matches))
                    for u in matches:
                        if u != own:
                            inv.refs[u].add(Ref(rel, i + 1, cat, "glob"))
                elif kind == "constructed":
                    inv.unresolved.append(Unresolved(
                        rel, i + 1, text, f"constructed path stops at {value}/; the code adds "
                        "the rest at run time"))
                elif kind == "outside":
                    inv.unresolved.append(Unresolved(rel, i + 1, text, value))
            if cat not in CITING:
                continue   # only machine-read files can decide a record's fate
            if not found and (m := MENTION.search(lines[i])):
                inv.unparsed.append(Unresolved(rel, i + 1, lines[i][m.start():][:50].strip(),
                                               "a root word with no path this script reads"))
            # A review mention the script cannot tie to a record is dropped only when the
            # line gives exactly one review by path and names at most one Codex review, so
            # that path is the mention's. Otherwise it is listed for reading by hand.
            explained = len(reviews_by_path) == 1 and len(CODEX.findall(lines[i])) <= 1
            for kind, value, text in _names(lines, i, reviews):
                if kind == "name" and value != own:
                    inv.refs[value].add(Ref(rel, i + 1, cat, "name"))
                elif kind == "ambiguous":
                    inv.ambiguous.append(Ambiguous(rel, i + 1, text, value))
                    for u in value:
                        inv.refs[u].add(Ref(rel, i + 1, cat, "ambiguous name"))
                elif kind == "unattributed" and not explained:
                    inv.unattributed.append(Unresolved(rel, i + 1, text, value))
    inv.unresolved = sorted(set(inv.unresolved))
    inv.ambiguous = sorted(set(inv.ambiguous))
    inv.unattributed = sorted(set(inv.unattributed))
    inv.globs = sorted(set(inv.globs))
    inv.unparsed = sorted(set(inv.unparsed))
    inv.undecodable.sort()
    return inv


STATUSES = ("cited", "cited by name", "possibly cited (ambiguous name)", "uncited",
            "uncited, no references")


def status(unit: str, inv: Inventory) -> str:
    refs = inv.refs.get(unit, set())
    citing = {r.how for r in refs if r.category in CITING}
    if citing & {"path", "glob"}:
        return "cited"
    if "name" in citing:
        return "cited by name"
    if "ambiguous name" in citing:
        return "possibly cited (ambiguous name)"
    return "uncited" if refs else "uncited, no references"


def counts_as_cited(s: str) -> bool:
    return s in STATUSES[:3]


def kept_units(inv: Inventory, units: list[str]) -> set[str]:
    """Records that stay in the tree: counted as cited, kept in place or active work."""
    return {u for u in units if counts_as_cited(status(u, inv)) or _note(u)}


def linked_from_kept(unit: str, inv: Inventory, units: list[str],
                     kept: set[str] | None = None) -> list[str]:
    """The kept records whose files refer to unit (by any kind of reference)."""
    kept = kept_units(inv, units) if kept is None else kept
    return sorted({o for r in inv.refs.get(unit, set())
                   if (o := unit_of(r.file)) and o != unit and o in kept})


def linked_from_docs(unit: str, inv: Inventory) -> str:
    """Which of doc and status (README, CLAUDE.md, docs/ but not docs/plans/) refer to it."""
    cats = {r.category for r in inv.refs.get(unit, set())}
    return ", ".join(c for c in ("doc", "status") if c in cats)


def _note(unit: str) -> str:
    notes = []
    if unit.split("/")[0] in KEPT_IN_PLACE:
        notes.append("kept in place (design section 6)")
    if unit in ACTIVE:
        notes.append("active work, stays where it is")
    return "; ".join(notes)


def _counts(refs: set[Ref]) -> list[str]:
    return [str(sum(r.category == c for r in refs) or "") for c in CATEGORIES]


def _where(refs: set[Ref]) -> list[str]:
    by_file: dict[tuple[str, str], list[int]] = defaultdict(list)
    for r in sorted(refs):
        by_file[(r.file, r.how)].append(r.line)
    return [f"- `{f}` ({category(f)}{'' if how == 'path' else ', ' + how}): lines "
            f"{', '.join(map(str, ls))}" for (f, how), ls in sorted(by_file.items())]


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("`", "")


def _lines(items: list[str], empty: str) -> list[str]:
    return [i + "\n" for i in items] if items else [empty + "\n"]


